#!/usr/bin/env node
// Copies runs' manifests and metrics into results/e1/<name>/ and writes
// REPORT.md from them. No number in the report is typed by hand. Step 20's
// model.json is copied too (aggregates only: coefficients, per-satellite
// effects and scales).
//
//   node experiments/e1-gps-epoch/steps/90-report.mjs --name a0 --runs <run-id>,<run-id>
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { repoRoot } from '../../../harness/provenance.mjs';

const { values } = parseArgs({ options: { name: { type: 'string' }, runs: { type: 'string' } } });
if (!values.name || !values.runs) throw new Error('--name and --runs are required');
const out = path.join(repoRoot, 'results/e1', values.name);
fs.mkdirSync(out, { recursive: true });

const runs = values.runs.split(',').map((id) => {
  const dir = path.join(repoRoot, 'runs', id);
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
  const metrics = JSON.parse(fs.readFileSync(path.join(dir, 'metrics.json'), 'utf8'));
  fs.mkdirSync(path.join(out, id), { recursive: true });
  for (const f of ['manifest.json', 'metrics.json', 'model.json']) {
    if (fs.existsSync(path.join(dir, f))) fs.copyFileSync(path.join(dir, f), path.join(out, id, f));
  }
  return { id, manifest, metrics };
});

const byAge = (o) => Object.entries(o).sort((a, b) => Number(a[0]) - Number(b[0]));
const km = (x, d = 3) => (Number.isFinite(x) ? x.toFixed(d) : '—');
const pct = (x) => (Number.isFinite(x) ? `${(100 * x).toFixed(1)} %` : '—');
const ci = (r) => `${pct(r.estimate)} [${pct(r.lower)}, ${pct(r.upper)}]`;
const lines = [`# E1 results: ${values.name}`, '', 'Generated by `experiments/e1-gps-epoch/steps/90-report.mjs` from the runs below. Do not edit by hand.', ''];

// ── Step 30: the evaluation ──
for (const r of runs.filter((x) => x.metrics.step === '30-evaluate')) {
  const m = r.metrics, H = m.hypotheses;
  const verdict = (h) => (H[h].supported ? '**supported**' : '**not supported**');
  lines.push(`## Evaluation on ${m.window.name} (${m.window.from} to ${m.window.to})`, '');
  lines.push(`Run \`${r.id}\`; freeze commit ${m.freezeCommit ? `\`${m.freezeCommit}\`` : 'none (dry run)'}; model \`${m.model.path}\` (SHA-256 \`${m.model.sha256}\`), M3* = \`${m.model.chosen}\`.`, '');
  const flagged = Object.entries(m.noHarm).filter(([, v]) => v.flagged).map(([t, v]) => `${t}: ${v.worse.length} satellites worse by more than 10 % (${v.worse.join(', ')})`);
  lines.push(`H1 is ${verdict('H1')}, H2 is ${verdict('H2')}, H3 is ${verdict('H3')}.` +
    (flagged.length ? ` No-harm flag: ${flagged.join('; ')}.` : ' No tier has more than one satellite made worse by more than 10 %.'), '');
  lines.push('Primary statistic: 3D RMS error at age 0 over the element sets M0\'s 5 robust-sigma clip keeps (amendment 2); R = 1 − RMS(method)/RMS(M0), paired. ' +
    `Intervals: ${Math.round(m.statistics.confidence * 100)} % percentile, two-way cluster bootstrap (satellite × day), ${m.statistics.resamples} resamples, seed ${m.statistics.seed}. ` +
    `Holm over H1–H3 at α = ${m.statistics.alpha}.`, '');
  lines.push('| Hypothesis | Tier | n | RMS M0 (km) | RMS method (km) | R [95 % interval] | Criterion | Holm p (threshold) | Result |', '| --- | --- | ---: | ---: | ---: | --- | --- | --- | --- |');
  const row = (h, tier, x, crit) => lines.push(`| ${h} | ${tier} | ${x.primary.n} | ${km(x.primary.rmsM0Km)} | ${km(x.primary.rmsKm)} | ${ci(x.primary.reduction)} | ${crit} | ${x.holm.pValue.toExponential(2)} (${x.holm.threshold.toFixed(4)}) | ${x.supported ? 'supported' : 'not supported'} |`);
  row('H1', 'G1, future time', H.H1, `R ≥ ${pct(H.H1.criteria.reductionAtLeast)}, lower ≥ ${pct(H.H1.criteria.lowerBoundAtLeast)}`);
  row('H2', 'G2, unseen plane', H.H2, `R ≥ ${pct(H.H2.criteria.reductionAtLeast)}, lower > ${pct(H.H2.criteria.lowerBoundAbove)}`);
  lines.push(`| H3 | G1, covariance | — | — | — | — | gate at ${byAge(H.H3.coverage).map(([a]) => a).join(', ')} d | ${H.H3.holm.pValue.toExponential(2)} (${H.H3.holm.threshold.toFixed(4)}) | ${H.H3.supported ? 'supported' : 'not supported'} |`, '');

  lines.push('### What can be checked without Space-Track', '',
    'The truth, Earth orientation and satellite identities are published in `data/e1/` and its release assets (`data/e1/SOURCES.md`), byte for byte as served, with the reference-states index of every product; `analysis/reference-states` rebuilds the reference states from them, and the modules are identified by WASM SHA-256 below. ' +
    'Every metric in this report scores Space-Track `gp_history` element sets, which Space-Track\'s terms keep off this repository: M0, M3a–c, G2, G3, M4\'s coverage and H1–H3 all need that history to reproduce. Each run manifest lists the SHA-256 of every `gp_history` file read, and the selection rules (PLAN.md §3) are deterministic, so anyone with a Space-Track account can retrieve the same records by creation date. ' +
    'CelesTrak\'s public GP service serves current element sets, not the 2024–2026 history, so no public GP source covers these epochs.', '');
  lines.push('### Every variant and tier, age 0 (descriptive beside the primary)', '',
    '| Method | n | RMS M0 | RMS method | R, primary (clipped) | R, every sample | R, 10 km rule |', '| --- | ---: | ---: | ---: | --- | --- | --- |');
  const all = [['M3a (Ly et al., reconstructed), G1', m.variants.M3a], ['M3b (Hallgarten La Casta & Amato), G1', m.variants.M3b], ['M3c (hierarchical harmonic), G1', m.variants.M3c],
    ['M3*, G2 unseen plane', H.H2], ['M3*, G3 unseen generation', m.g3]];
  for (const [name, x] of all) lines.push(`| ${name} | ${x.primary.n} | ${km(x.primary.rmsM0Km)} | ${km(x.primary.rmsKm)} | ${ci(x.primary.reduction)} | ${ci(x.everySample.reduction)} | ${ci(x.tenKmRule.reduction)} |`);
  lines.push('', `G3 satellites (launched ${'2018'} or later): ${m.g3Satellites.length}. GPS NANU sensitivity: ${m.sensitivityNanu}. H4: ${m.h4}.`, '');

  lines.push('### H3: coverage of the corrected product\'s covariance (M4)', '',
    'Every sample counts; d² = eᵀC⁻¹e by analysis/gp-error-model against χ²₃.', '',
    '| Age (d) | n | Objects | Inside 1σ / 2σ / 3σ | Nominal | Gate | Conformal 95 % coverage (target) |', '| ---: | ---: | ---: | --- | --- | --- | --- |');
  for (const [age, c] of byAge(H.H3.coverage)) {
    lines.push(`| ${age} | ${c.n} | ${c.objects} | ${c.inside.map((x) => x.toFixed(3)).join(' / ')} | ${c.nominal.map((x) => x.toFixed(3)).join(' / ')} | ${c.status} | ${c.conformal.coverage.toFixed(3)} (${c.conformal.target.join('–')}) |`);
  }
  lines.push('', `Bootstrap share of resamples in which the gate fails at some age: ${H.H3.bootstrap.failShare.toFixed(4)}.`, '');
  lines.push('Mean CRPS of M4 (km), R / T / N: ' + byAge(m.crps).map(([age, a]) => `${age} d: ${a.map((x) => km(x.meanCrpsKm, 4)).join(' / ')}`).join('; ') + '.', '');

  lines.push('### No-harm, per satellite (age 0, clipped)', '', '| Tier | Satellites | Worse by more than 10 % |', '| --- | ---: | --- |');
  for (const [tier, v] of Object.entries(m.noHarm)) lines.push(`| ${tier} | ${v.satellites} | ${v.worse.length ? v.worse.join(', ') : 'none'} |`);
  lines.push('');

  lines.push('### By age (clipped; descriptive)', '', '| Method | Age (d) | n | RMS 3D | M0 RMS 3D | RMS R / T / N | RMS 3D, every sample | Median 3D |', '| --- | ---: | ---: | ---: | ---: | --- | ---: | ---: |');
  for (const [method, list] of Object.entries(m.summary)) {
    for (const s of list.filter((x) => x.n)) lines.push(`| ${method} | ${s.ageDays} | ${s.n} | ${km(s.rms3dKm)} | ${km(s.rms3dM0Km)} | ${s.rmsRtnKm.map((x) => km(x)).join(' / ')} | ${km(s.rms3dAllKm)} | ${km(s.median3dKm)} |`);
  }
  lines.push('', '### The primary clip', '', '| Age (d) | M0 samples | Kept |', '| ---: | ---: | ---: |');
  for (const c of m.clip) lines.push(`| ${c.ageDays} | ${c.n} | ${c.kept} |`);
  lines.push('');
}

// ── Step 20: the fit ──
for (const r of runs.filter((x) => x.metrics.step === '20-fit')) {
  const m = r.metrics;
  lines.push(`## Fit on train (${m.windows.train.join(' to ')}), choice on validation (${m.windows.validation.join(' to ')})`, '');
  lines.push(`Run \`${r.id}\`. ${m.counts.trainSets} train and ${m.counts.validationSets} validation element sets. ` +
    `Along-track sensitivity measured by the module: ${km(m.sensitivity.medianKmPerS, 5)} km/s (range ${km(m.sensitivity.minKmPerS, 5)}–${km(m.sensitivity.maxKmPerS, 5)}, n = ${m.sensitivity.n}). ` +
    `Median |target| ${km(m.medianAbsTargetSeconds, 3)} s. M3* = \`${m.chosen}\`; best per variant: ${Object.entries(m.perVariant).map(([k, v]) => `${k} \`${v}\``).join(', ')}.`, '');
  lines.push('| Candidate | n | Validation RMS 3D (km) | M0 (km) | Reduction |', '| --- | ---: | ---: | ---: | ---: |');
  for (const s of m.selection) lines.push(`| ${s.id}${s.id === m.chosen ? ' (chosen)' : ''} | ${s.n} | ${km(s.rms3dKm, 4)} | ${km(s.rmsM0Km, 4)} | ${pct(s.reduction)} |`);
  lines.push('', '| Age (d) | M4 fit n | σ R / T / N at mean covariates (km) | Conformal radius (95 %) | Validation (second part) inside 1σ / 2σ / 3σ |', '| ---: | ---: | --- | ---: | --- |');
  for (const [age, v] of byAge(m.m4)) {
    lines.push(`| ${age} | ${v.n} | ${v.axes.map((a) => km(Math.exp(a.w[0]), 4)).join(' / ')} | ${km(m.conformal[age].radius)} | ${m.validationGate[age].inside.map((x) => x.toFixed(3)).join(' / ')} |`);
  }
  lines.push('', `Planes (train members per plane): ${m.planes.counts.join(', ')}. G3 train satellites: ${m.g3TrainSatellites}.`, '');
}

// ── Checks and the A0 baseline (step 05/10) ──
const withChecks = runs.filter((r) => Object.keys(r.metrics.checks ?? {}).length);
if (withChecks.length) {
  lines.push('## Checks', '', '| Check | Result | Detail | Run |', '| --- | --- | --- | --- |');
  for (const r of withChecks) {
    for (const [id, c] of Object.entries(r.metrics.checks)) {
      const detail = c.worstRelative !== undefined ? `worst relative difference ${c.worstRelative.toExponential(2)} (limit ${c.limit})` : '';
      lines.push(`| ${id} | ${c.pass ? 'PASS' : 'FAIL'} | ${c.description}; ${detail} | \`${r.id}\` |`);
    }
  }
  lines.push('', 'A0.1 (Vallado vectors) and A0.4 (determinism) are the end-to-end tests in `test/e2e.test.mjs`; their TAP output is saved beside this report as `e2e-test-output.tap`.', '');
}
for (const r of runs.filter((x) => x.metrics.summary && !x.metrics.step)) {
  const m = r.metrics;
  lines.push(`## ${m.method} on ${m.window.name} (${m.window.from} to ${m.window.to})`, '');
  lines.push(`${m.counts.sets} element sets, ${m.counts.samples} samples. Errors are prediction minus IGS truth, km; R radial, T along-track, N normal. ` +
    'Intervals are 95 % two-way cluster bootstrap (satellite × day).', '');
  lines.push('| Age (d) | n | Objects | RMS 3D | 95 % interval | RMS R / T / N | Median 3D | RMS 3D, 10 km rule (sensitivity) |', '| ---: | ---: | ---: | ---: | --- | --- | ---: | ---: |');
  for (const s of m.summary) {
    lines.push(`| ${s.ageDays} | ${s.n} | ${s.objects} | ${km(s.rms3dKm)} | ${km(s.rms3dCi.lower)} – ${km(s.rms3dCi.upper)} | ${s.rmsRtnKm.map((x) => km(x)).join(' / ')} | ${km(s.median3dKm)} | ${km(s.sensitivityTenKmRule?.rms3dKm)} (element sets dropped: ${s.sensitivityTenKmRule?.excludedSets ?? 0}) |`);
  }
  lines.push('', '### Per satellite, age 0', '', '| NORAD | n | Median along-track | RMS 3D |', '| ---: | ---: | ---: | ---: |');
  for (const o of m.perObject) lines.push(`| ${o.norad} | ${o.n} | ${km(o.medianAlongTrackKm)} | ${km(o.rms3dKm)} |`);
  lines.push('');
}

lines.push('## Provenance', '');
for (const r of runs) {
  const m = r.manifest;
  const products = Object.keys(m.inputs.referenceProducts ?? {});
  const byPrefix = {};
  for (const p of products) byPrefix[p.slice(0, 10)] = (byPrefix[p.slice(0, 10)] ?? 0) + 1;
  lines.push(`### \`${r.id}\``, '',
    `- Command: \`${m.command.join(' ')}\``,
    `- Config: \`${m.config.path}\` SHA-256 \`${m.config.sha256}\`, frozen: ${m.config.frozen}${m.freezeCommit ? `, freeze commit \`${m.freezeCommit}\`` : ''}`,
    `- This repository: ${m.repository.commit ?? `not committed (${m.repository.reason})`}${m.repository.dirty ? ', dirty' : ''}`,
    `- Modules repository: ${m.modulesRepository.commit ?? m.modulesRepository.reason}${m.modulesRepository.dirty ? ' (working tree dirty; module identity is the WASM hash below)' : ''}`,
    ...m.modules.map((x) => `- Module \`${x.path}\` ${x.pluginId} ${x.version}, WASM SHA-256 \`${x.wasmSha256}\``),
    `- Packages: ${Object.entries(m.packages).map(([k, v]) => `${k} ${v}`).join(', ')}`,
    `- Runtime: Node ${m.runtime.node}, ${m.runtime.platform}, ${m.runtime.cpus} CPUs`,
    ...(products.length ? [`- Reference products: ${Object.entries(byPrefix).map(([k, v]) => `${v} × ${k}`).join(', ')}`] : []),
    `- Inputs: ${Object.entries(m.inputs).map(([k, v]) => `${Object.keys(v).length} ${k}`).join(', ')} (hashes in manifest.json)`,
    `- Started ${m.started}, finished ${m.finished}`, '');
}
fs.writeFileSync(path.join(out, 'REPORT.md'), `${lines.join('\n')}\n`);
console.log(`wrote ${path.relative(repoRoot, out)}/REPORT.md`);
