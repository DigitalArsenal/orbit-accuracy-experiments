// Step 80: results/e16/README.md, generated from the selection and the test metrics (never typed), with the credit lines
// data/licenses.json owes for E16 (harness/credit-lines.mjs) on it and on the test report.
//
//   node experiments/e16-cross-regime-epoch/steps/80-readme.mjs
import fs from 'node:fs';
import path from 'node:path';
import { apply as applyCredits } from '../../../harness/credit-lines.mjs';
import { source } from '../../../harness/data-licenses.mjs';
import { SELECTION_FILE, readJson, repoRoot, resultsDir } from '../common.mjs';

const selection = readJson(path.join(repoRoot, SELECTION_FILE));
const metricsFile = path.join(resultsDir, 'test', 'metrics.json');
const metrics = fs.existsSync(metricsFile) ? readJson(metricsFile) : null;
const accept = Object.fromEntries(['q1', 'q2'].map((p) => [p, fs.existsSync(path.join(resultsDir, 'acceptance', `${p}.json`)) ? readJson(path.join(resultsDir, 'acceptance', `${p}.json`)) : null]));
const f = (x, d = 3) => (x === null || x === undefined || !Number.isFinite(x) ? '—' : x.toFixed(d));
const ci = (r, d = 3) => (r ? `${f(r.estimate ?? r.ratio, d)} [${f(r.lower, d)}, ${f(r.upper, d)}]` : '—');
const L = [];
L.push('# E16 results: start states from public OMMs across regimes, and transfer to unseen objects', '');
L.push('Plan: [experiments/e16-cross-regime-epoch/PLAN.md](../../experiments/e16-cross-regime-epoch/PLAN.md), frozen at `' + selection.freezeCommit + '`. Generated by step 80 from `selection.json` and `test/metrics.json`; do not edit by hand.', '');
if (metrics) {
  const h = metrics.hypotheses;
  const s = (x) => (x.supported ? 'supported' : 'not supported');
  L.push('## Hypotheses (test window, read once)', '', '| ID | Result | Statistic |', '| --- | --- | --- |');
  L.push(`| H1 (primary): LEO corrections transfer to unseen objects | ${s(h.H1)} | R ${ci(h.H1)} |`);
  L.push(`| H2: LEO transfers better than MEO/GEO | ${s(h.H2)} | ΔR ${ci(h.H2)} |`);
  L.push(`| H3: LEO corrections transfer to unseen operators | ${s(h.H3)} | R ${ci(h.H3)} |`);
  L.push(`| H4: LEO arc fits beat SGP4 at 24 h and 72 h | ${s(h.H4)} | A/S ${ci(h.H4.at24h, 2)} at 24 h, ${ci(h.H4.at72h, 2)} at 72 h |`);
  L.push(`| H5: E13's correction improves the arc fits | ${s(h.H5)} | ${ci(h.H5.at24h, 2)} at 24 h, ${ci(h.H5.at72h, 2)} at 72 h |`);
  L.push(`| H6: the corrected product's covariance is realistic (LEO, unseen) | ${s(h.H6)} | ${h.H6.verdict}; mean d²/3 ${ci(h.H6.meanD2Over3)} |`);
  const nh = metrics.q1.tiers.LEO.O.noHarm;
  L.push('', `No-harm rule (LEO tier O): ${nh.harmed} of ${nh.objects} held-out objects worse by more than 10 % (${nh.pass ? 'passes' : 'fails'}). Full tables: [test/REPORT.md](test/REPORT.md).`, '');
}
L.push('## Files', '', '| File | Contents |', '| --- | --- |');
L.push('| [inventory.json](inventory.json) | Every object, its class, orbit summary, SINEX block or Planet family, and its fold in every tier; the Q2 objects |');
L.push('| [selection.json](selection.json) | Every choice the test applies (committed before the test window was read): Q1\'s M* per group, Q2\'s span and B-dot per class, the test stride, A-corr\'s weights; SHA-256 of the files below |');
L.push('| [selection/q1.json](selection/q1.json) | Q1 on validation: every candidate\'s clipped RMS on held-out objects, the family bests, M4 |');
L.push('| [selection/q1-models.json](selection/q1-models.json) | The fitted models (coefficients, standardization, scales; per tier and fold) |');
L.push('| [selection/q2-train.json](selection/q2-train.json) | Q2\'s pseudo-observation weights and the inter-OMM correlation (train), its form (validation) |');
L.push('| [acceptance/](acceptance/) | Harness acceptance A1–A6 (PLAN.md 8) |');
L.push('| [test/REPORT.md](test/REPORT.md), [test/metrics.json](test/metrics.json) | The test window: every tier, class and product, with intervals |');
L.push('| [manifests/](manifests/) | Run manifests: commands, config hash, commits, module WASM SHA-256, every input\'s SHA-256 |', '');
if (accept.q1 || accept.q2) {
  L.push('## Acceptance', '', ...Object.values(accept).filter(Boolean).flatMap((a) => Object.entries(a.checks).map(([k, v]) => `- ${k}: ${v.pass === true ? 'pass' : v.pass === false ? '**fail**' : 'reported'}`)), '');
}
L.push('## Validation choices', '', `Q1 M*: LEO \`${selection.q1.LEO.chosen}\`; MEO/GEO \`${selection.q1['MEO/GEO'].chosen}\`. Q2: ${Object.entries(selection.q2.chosen).map(([c, v]) => `${c} ${v.spanDays} d${v.bdot ? ' with B-dot' : ''}`).join('; ')}; test stride ${selection.q2.testStrideDays} days.`, '');
L.push('## Data', '', 'Element sets (Space-Track), operator states (Planet, CC BY-NC 4.0) and the per-sample errors derived from them stay on this machine: only aggregates, fitted coefficients and manifests are committed. Results use every source.', '');
for (const id of ['planet', 'ids-doris', 'ucar-cosmic2', 'gfz-isdc-rso', 'nasa-cddis', 'igs', 'ilrs', 'ilrs-nsgf']) {
  try { L.push(`- ${source(id).credit}`); } catch { /* not registered */ }
}
L.push('');
const readme = path.join(resultsDir, 'README.md');
fs.writeFileSync(readme, `${L.join('\n')}\n`);
applyCredits(readme, 'E16');
if (fs.existsSync(path.join(resultsDir, 'test', 'REPORT.md'))) applyCredits(path.join(resultsDir, 'test', 'REPORT.md'), 'E16');
console.log(`wrote ${path.relative(repoRoot, readme)}`);
