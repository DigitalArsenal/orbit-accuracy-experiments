// The runner (PLAN.md sections 2-4). One window at cutoff E of a satellite, per arm: the fit of SRP's base arm on the last 24 h of the latest ESA arc ending by E (t_in), with Y0 fitted or fixed by lib/y0.mjs, and one FFM
// forecast from the fit with its covariance carried to the six leads; errors against ESA's next arcs and GFZ rapid orbits in the predicted RTN axes, by gp-error-model. FFM: RK78, relative tolerance 1e-10, steps up to 120 s;
// fit track at 600 s; outputs at the leads. Rows: <store>/rows/<phase>.s<k>.jsonl. Statistics live in dev.mjs and score.mjs.
//   node experiments/ffm-galileo-y-bias/run.mjs --launch --phase dev|arms [--workers 8]     detached, PID file <store>/logs/<phase>.pids.json
//   node experiments/ffm-galileo-y-bias/run.mjs --phase dev|arms --shard k/n [--limit m]
//   node experiments/ffm-galileo-y-bias/run.mjs --check                                     the E2E: a stored row per arm and block and one SRP base row replayed bit for bit, Y0 = 0 equal to no ECOM2, the values and table regenerated byte for byte, the guards live
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { config, store, results, root, dir, srp, c3, registered, registeredRef, commitOf, blockOf, dayMs, spanOf, gridOf, baseRows, devValues, Opened, args, sha256, HOUR, iso, readJsonl } from './common.mjs';
import { withY0 } from './lib/y0.mjs';

const { windowOf, msOf } = c3.chain;
const RUNNER = ['PLAN.md', 'config.json', 'build.json', 'common.mjs', 'run.mjs', 'lib/y0.mjs', 'lib/primary.mjs'];
const rowsDir = path.join(store, 'rows');
const TRUTH = srp.common.config.truth;
const unit = (a) => { const n = Math.hypot(...a); return a.map((x) => x / n); };
const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const m = (v) => v.map((x) => x * 1000);
const fitInput = (lines) => ({ points: lines.map((l) => ({ time: l.epoch, position: l.r.map((x) => x * 1000) })), reference: { epoch: lines[0].epoch, state: [...lines[0].r, ...lines[0].v].map((x) => x * 1000) } });

/** The arms of a phase on a block and span. */
const armsOf = (phase, block, span) => Object.keys(config.arms).filter((a) => config.arms[a].phase === phase && config.arms[a].blocks.includes(block) && config.arms[a].spans.includes(span));
/** Every window of a phase: satellite then date. */
export function windowsOf(phase) {
  return Object.keys(config.blocks).flatMap((block) => config.blocks[block].flatMap((norad) => ['dev', 'test'].flatMap((span) => (armsOf(phase, block, span).length ? gridOf(span).map((E) => ({ norad, block, span, E, arms: armsOf(phase, block, span) })) : []))));
}

/** The base arm's settings with an arm's Y0: 'B' none (the harness's own path); Yt, Y2, Yx fixed in the T slot; Y1 a parameter in it. */
export function armSettings(arm, norad, B2C, values) {
  const block = blockOf(norad), { seed, settings } = srp.run.armSettings(config.base.arms[block], norad, B2C);
  if (arm === 'B') return { seed, settings, y0: null, ctxOf: (ctx) => ctx };
  if (arm === 'Y1') {
    const a = config.arms.Y1, old = settings.apriori, k = 7, n = 8, diag = [...Array.from({ length: k }, (_, i) => old[i * k + i]), a.y0PriorSigma ** 2];
    return { seed, y0: null, ctxOf: withY0, settings: { ...settings, parameters: [...settings.parameters, { kind: 'IN_TRACK_ACCELERATION', value: a.y0Seed }], apriori: Array.from({ length: n * n }, (_, j) => (Math.floor(j / n) === j % n ? diag[j % n] : 0)) } };
  }
  const y0 = arm === 'Yt' ? config.arms.Yt.y0 : (arm === 'Yx' ? values.FOC : values[block]) * 1e-9;
  return { seed, y0, ctxOf: withY0, settings: { ...settings, fixed: { ...settings.fixed, t: y0 } } };
}

const session = async (opened) => srp.run.openSession(opened);

/** The rows of one window. */
export async function runWindow(S, { norad, block, span, E, arms }, values) {
  const win = windowOf(norad, S.arcsFor(norad), E, { leadToleranceSeconds: TRUTH.leadToleranceSeconds, leads_h: config.leads_h, minCoverage: TRUTH.minCoverage });
  const head = { norad, block, span, E: iso(E), tIn: win.tIn ?? null, product: win.product ?? null, coverage: win.coverage ?? null };
  if (win.excluded) return arms.map((arm) => ({ ...head, arm, excluded: win.excluded }));
  const tIn = win.tInMs, end = win.track.at(-1), sunM = await S.sunAt(tIn);
  const betaDeg = (Math.asin(dot(unit(sunM), unit(cross(end.r, end.v)))) * 180) / Math.PI;
  const ctx0 = S.chain.ctxFor(tIn - 24 * HOUR, tIn + 72 * HOUR), { points, reference } = fitInput(win.track);
  const leads = win.leads.filter((l) => l.line), epochs = leads.map((l) => msOf(l.line.epoch));
  const rows = [];
  for (const arm of arms) {
    const { seed, y0, settings, ctxOf } = armSettings(arm, norad, S.B2C, values), ctx = ctxOf(ctx0);
    const row = { ...head, arm, betaDeg, seed, seconds: {} };
    try {
      let t0 = Date.now();
      const f = await S.fitV3(ctx, points, reference, settings);
      row.seconds.fit = (Date.now() - t0) / 1000;
      const n = 6 + settings.parameters.length, cov = f.covariance?.length === n * n ? f.covariance : null;
      const sd = (i) => (cov ? Math.sqrt(cov[i * n + i]) : null);
      row.fit = { ok: f.ok, termination: f.termination ?? null, error: f.error ?? null, state: f.state ?? null, agom: f.parameters?.[0]?.value ?? null, agomSigma: sd(6), y0: y0 ?? f.parameters?.[1]?.value ?? null, y0Sigma: n === 8 ? sd(7) : null, corrY0Agom: n === 8 && cov ? cov[7 * n + 6] / (sd(7) * sd(6)) : null, reducedChiSquare: f.reducedChiSquare ?? null, weightedRms: f.weightedRms ?? null, iterations: f.iterations ?? null, ffmCalls: f.ffmCalls ?? null, rejectedTrials: f.rejectedTrials ?? null, refusedTrials: f.refusedTrials ?? null, covarianceSha256: f.covariance ? sha256(Buffer.from(Float64Array.from(f.covariance).buffer)) : null };
      if (f.ok) {
        t0 = Date.now();
        const carried = new Map((await c3.terms.carry(ctx, f, epochs, settings)).map((c) => [c.epochMs, c]));
        const pairs = [], keys = [];
        leads.forEach((l, i) => {
          const c = carried.get(epochs[i]), predicted = { position: c.state.slice(0, 3), velocity: c.state.slice(3, 6), covariance: c.covariance, covarianceAxes: 'INERTIAL' };
          pairs.push({ predicted, truth: { position: m(l.line.r), velocity: m(l.line.v) } }); keys.push([i, 'esa']);
          const g = S.gfzAt(norad, l.line.epoch);
          if (g) { pairs.push({ predicted, truth: { position: g.state.slice(0, 3), velocity: g.state.slice(3, 6) } }); keys.push([i, 'gfz']); }
        });
        const out = leads.map((l) => ({ L: l.L, epoch: l.line.epoch, errRtnM: null, gfzRtnM: null, covRtn: null }));
        (await S.chain.pairs.stats(pairs, 'predicted')).forEach((s, k) => { const [i, kind] = keys[k]; if (kind === 'esa') { out[i].errRtnM = s.errorRtn; out[i].covRtn = s.predictedRtn; } else out[i].gfzRtnM = s.errorRtn; });
        row.leads = out;
        row.seconds.forecast = (Date.now() - t0) / 1000;
      }
    } catch (error) { row.refused = String(error.message).slice(0, 240); }
    rows.push(row);
  }
  return rows;
}

const strip = (r) => { const { seconds, ...rest } = r; return rest; };
async function check() {
  registered([...RUNNER, 'dev-values.json', 'dev.mjs', 'score.mjs', 'report.mjs']);
  const failures = [];
  const refuses = (what, fn) => { try { fn(); failures.push(`${what}: not refused`); } catch { /* refused, as it must be */ } };
  const probe = new Opened();
  refuses('C3 rows', () => probe.add('/opt/data/sdn-archive/ffm-covariance-adaptive/rows/calibration.s0.jsonl'));
  refuses('C3 results', () => probe.add(path.join(root, 'results/ffm-covariance-adaptive/fit-R3.json')));
  refuses('C2 rows', () => probe.add('/opt/data/sdn-archive/ffm-covariance-calibration/rows/R3.calibration.s0.jsonl'));
  refuses('truth after 2026-05-31', () => c3.chain.arcsOf(54377, { fromMs: dayMs(TRUTH.arcsFrom), toMs: dayMs('2026-06-15'), allowedToMs: dayMs(TRUTH.allowedTo) + 86400e3 }));
  const rows = fs.existsSync(rowsDir) ? fs.readdirSync(rowsDir).filter((f) => f.endsWith('.jsonl')).sort().flatMap((f) => readJsonl(path.join(rowsDir, f))) : [];
  if (!rows.length) { console.error(`--check needs this experiment's rows: none under ${rowsDir}. Not a pass.`); process.exit(2); }
  const want = ['dev', 'arms'].flatMap((ph) => windowsOf(ph).flatMap((w) => w.arms.map((a) => `${w.norad}|${iso(w.E)}|${a}`))), have = new Set(rows.map((r) => `${r.norad}|${r.E}|${r.arm}`));
  if (have.size !== rows.length) failures.push(`${rows.length} rows, ${have.size} distinct`);
  for (const k of want) if (!have.has(k)) failures.push(`no row for ${k}`);
  // one stored window per block and every arm of it, bit for bit; and SRP's base row through this runner, with Y0 = 0 through the adapter on the same state
  const opened = new Opened(), S = await session(opened), values = devValues(), base = baseRows(opened), seen = [];
  for (const [norad, day] of [[41549, '2026-01-25'], [37846, '2026-01-25'], [54377, '2026-01-25']]) {
    const E = dayMs(day), span = spanOf(E), block = blockOf(norad);
    for (const g of await runWindow(S, { norad, block, span, E, arms: armsOf('arms', block, span) }, values)) {
      const stored = rows.find((x) => x.norad === g.norad && x.E === g.E && x.arm === g.arm);
      seen.push(`${g.arm}/${block}`);
      if (JSON.stringify(strip(g)) !== JSON.stringify(strip(stored))) failures.push(`${g.arm} ${g.norad} ${g.E}: the replayed row differs from the stored row`);
    }
    const [b] = await runWindow(S, { norad, block, span, E, arms: ['B'] }, values), stored = base.get(`${norad}|${iso(E)}`);
    if (JSON.stringify(b.fit.state) !== JSON.stringify(stored.fit.state) || b.fit.agom !== stored.fit.agom || JSON.stringify(b.leads.map((l) => [l.errRtnM, l.gfzRtnM, l.covRtn])) !== JSON.stringify(stored.leads.map((l) => [l.errRtnM, l.gfzRtnM, l.covRtn]))) failures.push(`base ${norad} ${day}: this runner does not replay SRP's row`);
    const zero = await S.fitV3(withY0(S.chain.ctxFor(Date.parse(b.tIn) - 24 * HOUR, Date.parse(b.tIn) + 72 * HOUR)), ...(() => { const win = windowOf(norad, S.arcsFor(norad), E, { leadToleranceSeconds: TRUTH.leadToleranceSeconds, leads_h: config.leads_h, minCoverage: TRUTH.minCoverage }), { points, reference } = fitInput(win.track), a = armSettings('B', norad, S.B2C, values); return [points, reference, { ...a.settings, fixed: { ...a.settings.fixed, t: 0 } }]; })());
    if (JSON.stringify(zero.state) !== JSON.stringify(b.fit.state)) failures.push(`${norad} ${day}: Y0 = 0 through the adapter differs from no ECOM2`);
  }
  // the values and the table, byte for byte
  const { computeDevValues } = await import('./dev.mjs');
  const { buildTable, renderTable } = await import('./score.mjs');
  if (`${JSON.stringify(computeDevValues(new Opened()), null, 1)}\n` !== fs.readFileSync(path.join(dir, 'dev-values.json'), 'utf8')) failures.push('dev-values.json differs from the values regenerated from the dev rows');
  const table = buildTable(new Opened()), tableFile = path.join(results, 'table.json');
  if (!fs.existsSync(tableFile)) failures.push(`no ${tableFile}`);
  else if (`${JSON.stringify(table, null, 1)}\n` !== fs.readFileSync(tableFile, 'utf8')) failures.push('table.json differs from the table regenerated from the rows');
  else if (renderTable(table) !== fs.readFileSync(path.join(results, 'table.md'), 'utf8')) failures.push('table.md differs from the table rendered from table.json');
  else {
    const { renderReadme } = await import('./report.mjs');
    if (renderReadme(table) !== fs.readFileSync(path.join(results, 'README.md'), 'utf8')) failures.push('README.md differs from the report rendered from the table');
  }
  if (failures.length) { console.error(failures.slice(0, 30).join('\n')); process.exit(1); }
  console.log(`Y --check: ${rows.length} rows; ${seen.join(', ')} replayed bit for bit at ${commitOf().slice(0, 12)}; SRP's base rows replayed; Y0 = 0 equals no ECOM2; values, table and README regenerated byte for byte; the guards refuse C3's and C2's rows and results and truth after ${TRUTH.allowedTo}`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (args.check) { await check(); process.exit(0); }
  registered(RUNNER);
  const phase = args.phase;
  if (!['dev', 'arms'].includes(phase)) { console.error('--launch --phase dev|arms | --phase dev|arms --shard k/n | --check'); process.exit(2); }
  if (phase === 'arms') devValues();
  if (args.launch) {
    const workers = Number(args.workers ?? config.workers);
    if (workers > 8) throw new Error('at most 8 workers');
    fs.mkdirSync(path.join(store, 'logs'), { recursive: true });
    const pids = [];
    for (let k = 0; k < workers; k += 1) {
      const log = fs.openSync(path.join(store, 'logs', `${phase}.s${k}.log`), 'a');
      const p = spawn('nice', ['-n', '5', process.execPath, '--max-old-space-size=4096', path.join(dir, 'run.mjs'), '--phase', phase, '--shard', `${k}/${workers}`], { cwd: root, detached: true, stdio: ['ignore', log, log], env: process.env });
      p.unref();
      pids.push({ pid: p.pid, shard: `${k}/${workers}` });
    }
    fs.writeFileSync(path.join(store, 'logs', `${phase}.pids.json`), JSON.stringify({ started: new Date().toISOString(), registeredRef, commit: commitOf(), pids }, null, 1));
    console.log(JSON.stringify(pids));
    process.exit(0);
  }
  const opened = new Opened();
  const [k, n] = (args.shard ?? '0/1').split('/').map(Number);
  fs.mkdirSync(rowsDir, { recursive: true });
  const out = path.join(rowsDir, `${phase}.s${k}.jsonl`);
  const done = new Set(readJsonl(out).map((r) => `${r.norad}|${r.E}|${r.arm}`));
  const S = await session(opened), values = phase === 'arms' ? devValues() : null, windows = windowsOf(phase);
  let count = 0;
  for (let i = 0; i < windows.length; i += 1) {
    const w = windows[i];
    if (i % n !== k) continue;
    if (args.limit && count >= Number(args.limit)) break;
    if (w.arms.every((a) => done.has(`${w.norad}|${iso(w.E)}|${a}`))) continue;
    const t0 = Date.now();
    const rows = await runWindow(S, w, values);
    fs.appendFileSync(out, rows.filter((r) => !done.has(`${r.norad}|${r.E}|${r.arm}`)).map((r) => `${JSON.stringify(r)}\n`).join(''));
    count += 1;
    if (count % 10 === 0) console.error(`${phase} shard ${k}/${n}: ${count} windows, last ${w.norad} ${iso(w.E).slice(0, 10)}, ${((Date.now() - t0) / 1000).toFixed(1)} s`);
  }
  fs.mkdirSync(path.join(store, 'opened'), { recursive: true });
  fs.writeFileSync(path.join(store, 'opened', `${phase}.s${k}.json`), JSON.stringify(opened.list()));
  console.error(`${phase} shard ${k}/${n}: finished, ${count} windows`);
  process.exit(0);
}
