#!/usr/bin/env node
// Publishes every non-Space-Track input E2 uses, for others to check:
// data/e2/MANIFEST.json and data/e2/SOURCES.md (git), small files compressed
// under data/e2/ (git), and large files copied to --assets DIR for upload as
// release assets. Space-Track element sets are never published (aggregates
// only, under results/e2).
//
//   node experiments/e2-catalog-covariance/publish-data.mjs --assets <dir>
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { parseArgs } from 'node:util';
import { sha256 } from '../../harness/modules.mjs';
import { repoRoot } from '../../harness/provenance.mjs';
import { DAY_MS, config } from './common.mjs';

const { values } = parseArgs({ options: { assets: { type: 'string' } } });
if (!values.assets) throw new Error('--assets DIR (large files for release upload) is required');
const out = path.join(repoRoot, 'data', 'e2');
fs.mkdirSync(out, { recursive: true });
fs.mkdirSync(values.assets, { recursive: true });
const entries = [];
const stat = (file) => fs.statSync(file);
const add = (entry) => entries.push(entry);

// Precise orbits: the SP3 products whose converted states any window reads
// (window start minus a day to window end plus the longest horizon plus a day).
const referenceDir = config.inputs.reference;
const productsDir = path.join(path.dirname(referenceDir), 'products');
const horizon = Math.max(...config.products.horizonsDays) + 1;
for (const [name, [from, to]] of Object.entries(config.windows)) {
  const lo = Date.parse(`${from}T00:00:00Z`) - DAY_MS, hi = Date.parse(`${to}T00:00:00Z`) + (horizon + 1) * DAY_MS;
  for (const regime of Object.values(config.regimes)) {
    for (const product of fs.readdirSync(referenceDir).filter((n) => n.startsWith(regime.productPrefix)).sort()) {
      const indexFile = path.join(referenceDir, product, 'index.json');
      if (!fs.existsSync(indexFile)) continue;
      const index = JSON.parse(fs.readFileSync(indexFile, 'utf8'));
      const start = Math.min(...index.objects.map((o) => Date.parse(o.start)));
      if (!(start >= lo && start < hi)) continue;
      const source = path.join(productsDir, index.product);
      if (!fs.existsSync(source) || entries.some((e) => e.name === index.product)) continue;
      const bytes = fs.readFileSync(source);
      if (sha256(bytes) !== index.sha256) throw new Error(`${index.product}: bytes differ from the converted index`);
      fs.copyFileSync(source, path.join(values.assets, index.product));
      add({ name: index.product, kind: 'precise orbit (SP3)', windows: [name], url: index.url, sha256: index.sha256, bytes: bytes.length,
        retrieved: stat(source).mtime.toISOString(), location: 'release-asset', terms: 'ESA/ESOC GNSS products (navigation-office.esa.int), free use with attribution; IGS data policy' });
    }
  }
}
for (const e of entries) e.windows = [...new Set(entries.filter((x) => x.name === e.name).flatMap((x) => x.windows))];

// Earth orientation: IERS finals2000A, gzip in git.
const eop = config.inputs.eopFinals;
const eopBytes = fs.readFileSync(eop);
fs.writeFileSync(path.join(out, `${path.basename(eop)}.gz`), zlib.gzipSync(eopBytes, { level: 9 }));
add({ name: path.basename(eop), kind: 'Earth orientation (IERS finals2000A)', url: 'https://datacenter.iers.org/data/9/finals2000A.all', sha256: sha256(eopBytes), bytes: eopBytes.length,
  retrieved: stat(eop).mtime.toISOString(), location: `git: data/e2/${path.basename(eop)}.gz`, terms: 'IERS Earth Orientation Centre; free use with citation of the IERS' });

// Sun and Moon: JPL DE440s, release asset.
const kernel = path.join(repoRoot, config.inputs.kernel.path);
fs.copyFileSync(kernel, path.join(values.assets, path.basename(kernel)));
add({ name: path.basename(kernel), kind: 'planetary ephemeris (JPL DE440s)', url: config.inputs.kernel.url, sha256: config.inputs.kernel.sha256, bytes: stat(kernel).size,
  retrieved: stat(kernel).mtime.toISOString(), location: 'release-asset', terms: 'NASA/JPL NAIF generic kernels, public' });

const manifest = { experiment: config.experiment, generated: new Date().toISOString(), note: 'Space-Track element sets are not published; results/e2 holds aggregates only.', files: entries };
fs.writeFileSync(path.join(out, 'MANIFEST.json'), `${JSON.stringify(manifest, null, 1)}\n`);
const assetBytes = entries.filter((e) => e.location === 'release-asset').reduce((a, e) => a + e.bytes, 0);
const lines = ['# E2 input data', '', 'Every input of experiment E2 that is not a Space-Track element set. Generated by `experiments/e2-catalog-covariance/publish-data.mjs`; `MANIFEST.json` lists each file with its SHA-256.', '',
  `- Precise orbits: ${entries.filter((e) => e.kind.startsWith('precise')).length} ESA final GNSS orbit products (\`ESA0OPSFIN\`, SP3, 5 min), from https://navigation-office.esa.int/products/gnss-products/; release assets (${(assetBytes / 1e6).toFixed(0)} MB with the kernel). Terms: ESA/ESOC GNSS products, free use with attribution; IGS data policy.`,
  `- Earth orientation: IERS \`finals2000A.all\` (${path.basename(eop)}), in git as \`data/e2/${path.basename(eop)}.gz\`. Source https://datacenter.iers.org/data/9/finals2000A.all. Terms: free use with citation of the IERS.`,
  `- Sun and Moon: JPL DE440s (\`de440s.bsp\`), ${config.inputs.kernel.url}; release asset. Terms: NASA/JPL NAIF, public.`,
  '- Space weather and JB2008 indices: none; the regimes E2 tests (GPS) have no drag.',
  '- Element sets: Space-Track `gp_history`, not redistributed (Space-Track user agreement); only aggregates are published.', '',
  'Retrieval times are the files\' modification times on the archive host, as listed in `MANIFEST.json`.', ''];
fs.writeFileSync(path.join(out, 'SOURCES.md'), lines.join('\n'));
console.log(`${entries.length} files; ${(assetBytes / 1e6).toFixed(1)} MB of release assets in ${values.assets}`);
