// C2's table (PLAN.md 4): every held-out cell of every frozen class, from the held-out receipts, as table.json. Records only.
//   node experiments/ffm-covariance-calibration/table.mjs [--check]   (--check: regenerate and compare with the committed table.json)
import fs from 'node:fs';
import path from 'node:path';
import { results, args } from './common.mjs';

export function buildTable() {
  const files = fs.readdirSync(results).filter((f) => /^heldout-[A-Za-z0-9-]+\.json$/.test(f)).sort();
  const classes = {};
  for (const f of files) {
    const t = JSON.parse(fs.readFileSync(path.join(results, f)));
    classes[f.replace(/^heldout-|\.json$/g, '')] = Object.fromEntries(Object.entries(t.variants).map(([v, x]) => [v, {
      windows: x.counts.windows, failures: (x.counts.failures ?? []).length, eligibleCells: x.eligibleCells, passingEligibleCells: x.passingEligibleCells,
      leads: Object.fromEntries(Object.entries(x.leads).map(([L, q]) => [L, { n: q.n, clusters: q.clusters, meanD2over3: q.meanD2over3, meanInterval: q.meanInterval, medianD2over3: q.medianD2over3,
        coverage: q.coverage, coverageInterval: q.coverageInterval, meanZ2Rtn: q.meanZ2Rtn, oraclePassProbability: q.oraclePassProbability, label: q.label }])),
    }]));
  }
  return { table: 'C2 held-out cells (each class scored once; type I and L-P run 2, C2-A5; S robustness only, C2-A8)', frozenConstants: 'frozen-constants.json', classes };
}
const file = path.join(results, 'table.json');
const text = `${JSON.stringify(buildTable(), null, 1)}\n`;
if (args.check) {
  if (fs.readFileSync(file, 'utf8') !== text) { console.error('table.json differs from its regeneration'); process.exit(1); }
  console.log('table.json regenerated byte-identical');
} else { fs.writeFileSync(file, text); console.log(file); }
