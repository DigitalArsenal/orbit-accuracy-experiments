// E13 step 90: the report of one split, generated from the result files of steps 30 and 50 (and, for dev, 12 and 45), the selection and the run manifests:
// results/e13/<split>/REPORT.md and metrics.json; the manifests of the runs behind the numbers are copied to results/e13/manifests/. Numbers are copied, never
// recomputed, except the Holm step over H3, H4 (one day) and H5 (one day).
//
//   node steps/90-report.mjs --split dev|testA|testB
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { repoRoot } from '../../../harness/provenance.mjs';
import { config } from '../common.mjs';
import { holm } from '../score.mjs';

const { values } = parseArgs({ options: { split: { type: 'string' } } });
const resultsDir = process.env.E13_RESULTS ?? path.join(repoRoot, 'results', 'e13');      // E13_RESULTS: a scratch folder for a development run
const split = values.split, dir = path.join(resultsDir, split);
const read = (f) => (fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : null);
const selection = read(path.join(resultsDir, 'selection.json'));
const density = read(path.join(dir, 'density-score.json')), prop = read(path.join(dir, 'propagation-score.json'));
const cr = read(path.join(dir, 'cr-sensitivity.json')), diag = read(path.join(dir, 'diagnostics.json'));
if (!density) throw new Error(`no density-score.json for ${split}`);
const [from, to] = config.planet.split[split];
const f = (x, d = 3) => (Number.isFinite(x) ? x.toFixed(d) : 'n/a');
const ci = (e, l, u, d = 3) => `${f(e, d)} [${f(l, d)}, ${f(u, d)}]`;
const L = [];

L.push(`# E13 ${split} report`, '', `Generated by \`experiments/e13-open-dca/steps/90-report.mjs\` from the result files in this folder; every number is a step's output. Span ${from}..${to}.`, '',
  `Solver (chosen on the dev split, \`../selection.json\`): ${selection.solver.label}; forecast time constant ${selection.tauHours === null ? 'held' : `${selection.tauHours} h`}. Arcs: ${density.arcs.calibration} of the calibration Doves, ${density.arcs.heldOut} of the held-out Doves; robust scatter of an arc about its baseline and the common mode ${f(density.sigmaArc, 4)}; ${density.sweeps} sweeps${density.converged ? '' : ' (not converged)'}.`, '');

// H1, H6
const h1 = density.H1, h6 = density.H6;
L.push('## H1 density: spread reduction against Swarm A, B, C and GRACE-FO 1', '',
  `R1 = 1 - sd(x' - s) / sd(x') over ${h1.n} 12 h windows: **${ci(h1.R1, h1.interval.lower, h1.interval.upper)}** (sd ${f(h1.sdX, 4)} to ${f(h1.sdRes, 4)}); threshold ${h1.thresholdR1} with the lower bound above 0: **${h1.supported ? 'supported' : 'not supported'}**.`, '',
  '| Satellite | Windows | R1 | Slope of x\' on s | Correlation |', '| --- | ---: | ---: | ---: | ---: |',
  ...Object.entries(h1.perSatellite).map(([k, v]) => `| ${k} | ${v.n} | ${f(v.R1, 3)} | ${f(v.slope, 2)} | ${f(v.corr, 2)} |`), '',
  `H6 control (s shifted by ${h6.shiftDays} d): R1 ${f(h6.R1, 3)} over ${h6.n} windows; required below ${config.analysis.hypotheses.H6.maximumReduction}: **${h6.passes ? 'passes' : 'fails'}**.`, '');

// H2
const h2 = density.H2;
L.push('## H2 storm capture (descriptive)', '', `Storm days (GFZ daily Ap at least ${config.analysis.stormApAtLeast}): ${Object.entries(h2.stormDays).map(([d, ap]) => `${d} (Ap ${ap})`).join(', ') || 'none'}.`, '');
if (h2.windows) {
  L.push(`${h2.windows} windows: s has the sign of x' in ${f(100 * h2.sameSignShare, 0)} %; median s / x' ${f(h2.medianCapture, 2)} over the ${h2.nBig} windows with |x'| > 0.1 (captured if at least ${100 * config.analysis.hypotheses.H2.sameSignShare} % and ${config.analysis.hypotheses.H2.medianCapture}).`, '',
    '| Satellite | Window start (UTC) | x\' | s |', '| --- | --- | ---: | ---: |', ...h2.list.map((w) => `| ${w.key} | ${w.start.slice(0, 16)} | ${f(w.xp, 3)} | ${f(w.sbar, 3)} |`), '');
}

// H3
const h3 = density.H3;
L.push('## H3 held-out Doves (hindcast)', '', h3
  ? `${h3.arcs} arcs of the held-out Doves: R3 = 1 - MAD(u - s) / MAD(u) = **${ci(h3.R3, h3.lower, h3.upper)}** (MAD ${f(h3.madD0, 4)} to ${f(h3.madD13, 4)}); threshold ${h3.thresholdR3} with the lower bound above 0: **${h3.supported ? 'supported' : 'not supported'}**.`
  : 'No held-out arcs.', '');

// H4, H5
const tests = [];
if (h3) tests.push({ id: 'H3', p: h3.p });
if (prop) {
  for (const [target, t] of Object.entries(prop.targets)) {
    L.push(`## ${t.hypothesis} ${target === 'swarm' ? 'Swarm A, B, C' : 'held-out Doves'}: propagation`, '',
      `Median over paired (object, issue) of the 3D error of the variant divided by that of D0 (JB2008 with SET's indices); supported at a horizon if at most ${config.analysis.hypotheses[t.hypothesis].threshold} with the upper bound below 1. Objects: ${t.objects.join(', ')}.`, '',
      '| Horizon | Variant | Pairs | Median ratio [95 %] | One-sided p | Median error D0 (m) | Median error variant (m) | Improved | Verdict |', '| --- | --- | ---: | --- | ---: | ---: | ---: | ---: | --- |');
    for (const [h, res] of Object.entries(t.horizons)) {
      for (const [variant, r] of Object.entries(res)) {
        if (r.estimate === undefined) { L.push(`| ${h} d | ${variant} | ${r.pairs} | too few | | | | | |`); continue; }
        L.push(`| ${h} d | ${variant} | ${r.pairs} | ${ci(r.estimate, r.lower, r.upper)} | ${f(r.p, 4)} | ${f(r.medianErrorM.D0, 0)} | ${f(r.medianErrorM[variant], 0)} | ${f(100 * r.shareImproved, 0)} % | ${variant === 'D13' ? (r.supported ? 'supported' : 'not supported') : 'bound'} |`);
      }
    }
    L.push('');
    if (t.horizons[1]?.D13?.p !== undefined) tests.push({ id: t.hypothesis, p: t.horizons[1].D13.p });
    if (t.errorRows.length) L.push(`${t.errorRows.length} job rows ended in an error (first: ${t.errorRows[0].error}).`, '');
  }
}
const holmRows = tests.length ? holm(tests) : [];
if (holmRows.length) L.push('## Holm over H3, H4 (one day) and H5 (one day)', '', '| Test | One-sided p | Threshold | Rejects |', '| --- | ---: | ---: | --- |', ...holmRows.map((t) => `| ${t.id} | ${f(t.p, 4)} | ${f(t.threshold, 4)} | ${t.reject ? 'yes' : 'no'} |`), '');

// descriptive
L.push('## Descriptive', '', `Planet's own ballistic coefficient column in place of ours: R1 ${f(density.descriptive.planetColumnR1, 3)} over ${density.descriptive.planetColumnWindows} windows; correlation of the two common modes ${f(density.descriptive.correlationOfCommonModes, 3)}.`, '');
if (cr) L.push('## Cr·A/m sensitivity (dev)', '', `${cr.summary.arcs} arcs read again with Cr·A/m times 0.5 and 1.5: median |change in ln Cd·A/m| ${f(100 * cr.summary.medianAbsLnChangeLow, 2)} % and ${f(100 * cr.summary.medianAbsLnChangeHigh, 2)} %, at most ${f(100 * Math.max(cr.summary.maxAbsLnChangeLow, cr.summary.maxAbsLnChangeHigh), 2)} %.`, '');
if (diag) L.push('## Dev diagnostics', '', `Baseline steps (|step| > 2.5 q sqrt(dt)): ${diag.steps.count} in ${diag.arcs} arcs (${f(diag.steps.perDoveDay, 4)} per Dove-day); dispersion index of steps per day ${f(diag.steps.dispersionIndex, 2)} (1 for independent steps); mean pairwise correlation of the Doves' residuals ${diag.residualCorrelation.meanPairwise === null ? 'n/a' : f(diag.residualCorrelation.meanPairwise, 3)}; stated relative sigma of an arc ${f(diag.statedVersusRealised.statedMedianRelativeSigma, 3)} against a realised ${f(diag.statedVersusRealised.realisedRobustSigma, 3)}.`, '');

fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'REPORT.md'), `${L.join('\n')}\n`);
fs.writeFileSync(path.join(dir, 'metrics.json'), `${JSON.stringify({ split, span: [from, to], selection: selection.solver, tauHours: selection.tauHours, density, propagation: prop, holm: holmRows, crSensitivity: cr?.summary ?? null, diagnostics: diag }, null, 1)}\n`);

// the manifests behind the numbers
const runIds = new Set([density.run, ...(prop?.runs ?? []).map((r) => r.run), selection.run].filter(Boolean));
const manifests = path.join(resultsDir, 'manifests');
fs.mkdirSync(manifests, { recursive: true });
let copied = 0;
for (const id of runIds) {
  const src = path.join(repoRoot, 'runs', id, 'manifest.json');
  if (fs.existsSync(src)) { fs.copyFileSync(src, path.join(manifests, `${id}.manifest.json`)); ++copied; }
}
console.log(`${dir}: REPORT.md and metrics.json; ${copied} of ${runIds.size} manifests copied`);
