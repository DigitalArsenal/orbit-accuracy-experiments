#!/usr/bin/env node
// E13 step 95: E13's inputs under the owner's data policy (2026-10-10): the results use every input, whatever its licence; only sources that data/licenses.json
// marks reproducible may be copied into the repository, and E13 copies nothing (Planet's states are CC BY-NC and the per-satellite-day fits derived from them stay
// on the machine; SpaceX's files are never stored; ESA's densities and orbits and SET's indices are cited by URL and SHA-256). Writes data/e13/MANIFEST.json (every
// input file of the runs in results/e13/manifests, by family and licence source, with its SHA-256 and the runs that read it) and data/e13/SOURCES.md.
//
//   node experiments/e13-open-dca/steps/95-sources.mjs
import fs from 'node:fs';
import path from 'node:path';
import { repoRoot } from '../../../harness/provenance.mjs';
import { licenseSection, source } from '../../../harness/data-licenses.mjs';

const dir = path.join(repoRoot, 'results/e13/manifests');
const out = path.join(repoRoot, 'data/e13');

// The licence source of each input file (data/licenses.json ids; null: this repository's own runs and code).
function sourceOf(family, file) {
  switch (family) {
    case 'planet': case 'planet-live': return 'planet';
    case 'set': return 'set-jb2008';
    case 'gfz': return 'gfz-kp';
    case 'eop': return 'iers';
    case 'kernel': return 'jpl-de440';
    case 'reference': if (/^SW_OPER_/.test(file.split('/')[0])) return 'esa-earth-observation'; throw new Error(`reference ${file}: no licence source`);
    case 'planet-arcs': case 'selection': case 'amendments': case 'code': return null;
    default:
      if (family.startsWith('densities-')) return 'esa-earth-observation';
      throw new Error(`input family ${family}: no licence source`);
  }
}

const files = {};
for (const name of fs.readdirSync(dir).filter((n) => n.endsWith('.manifest.json')).sort()) {
  const m = JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8'));
  for (const [family, entries] of Object.entries(m.inputs ?? {})) {
    for (const [file, hash] of Object.entries(entries)) {
      const key = `${family}/${file}`;
      files[key] ??= { family, file, source: sourceOf(family, file), sha256: hash, runs: [] };
      if (files[key].sha256 !== hash) files[key].conflict = true;
      files[key].runs.push(m.run);
    }
  }
}
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'MANIFEST.json'), `${JSON.stringify({ generated: new Date().toISOString(), files: Object.values(files) }, null, 1)}\n`);

const bySource = Object.values(files).reduce((a, f) => { (a[f.source ?? 'this repository'] ??= []).push(f); return a; }, {});
const registered = [...new Set([...Object.keys(bySource).filter((id) => id !== 'this repository'), 'spacex-starlink'])].sort();
const lines = ['# E13 inputs', '',
  'Generated by `experiments/e13-open-dca/steps/95-sources.mjs` from the run manifests in `results/e13/manifests`. E13\'s results use every input below, whatever its licence. Nothing is copied into this repository: every input file, with its licence source, SHA-256 and the runs that read it, is in [MANIFEST.json](MANIFEST.json). Planet\'s states and the per-satellite-day fits derived from them, and SpaceX\'s files, stay on the machine that ran E13; only aggregate statistics are published.', '',
  '## Every input, by source', '', '| Source | Files | Reproduced | Families |', '| --- | ---: | --- | --- |'];
const verdictOf = { yes: 'Yes, with attribution (nothing copied here)', 'non-commercial': 'Yes, with attribution, for non-commercial use only (nothing copied here)', 'share-alike': 'Yes, with attribution (share-alike; nothing copied here)', no: 'No: cited only' };
for (const [id, list] of Object.entries(bySource).sort()) {
  const fams = [...new Set(list.map((f) => f.family))].join(', ');
  lines.push(`| ${id === 'this repository' ? 'This repository' : source(id).name} | ${list.length} | ${id === 'this repository' ? 'this repository (MIT): E13\'s own runs and code' : verdictOf[source(id).reproduce]} | ${fams} |`);
}
lines.push(`| ${source('spacex-starlink').name} | read by the collector, not in a run manifest | ${verdictOf[source('spacex-starlink').reproduce]}; the collector stores derived records only | collector (\`collect.mjs\`), steps/60 |`);
lines.push('', ...licenseSection(registered, 'data/e13'));
const conflicts = Object.values(files).filter((f) => f.conflict);
if (conflicts.length) lines.push('', `Inputs read with different SHA-256 by different runs: ${conflicts.map((f) => `\`${f.family}/${f.file}\``).join(', ')}.`);
fs.writeFileSync(path.join(out, 'SOURCES.md'), `${lines.join('\n')}\n`);
console.log(`data/e13: ${Object.keys(files).length} input files from ${Object.keys(bySource).length} sources`);
