#!/usr/bin/env node
// E8 step 95: the inputs of E8's committed runs, listed (never copied):
// data/e8/MANIFEST.json (every input file with its SHA-256, by family, and the
// runs that read it) and data/e8/SOURCES.md generated from it with each
// family's source and terms. Element sets appear by file name and hash only.
//
//   node .../95-sources.mjs
import fs from 'node:fs';
import path from 'node:path';
import { repoRoot } from '../../../harness/provenance.mjs';

const dir = path.join(repoRoot, 'results/e8/manifests');
const FAMILIES = {
  elementSetFiles: ['Space-Track gp_history (by creation day) and GP history 1959-2022', 'Space-Track user agreement; element sets stay on this machine, listed here by hash only'],
  elementSetCache: ['E8 step 05 caches of the element sets above (runs/cache, not published)', 'as above'],
  catalogs: ['Space-Track SATCAT snapshot 2026-10-09; GCAT satcat.tsv 2026-10-08 (planet4589.org/space/gcat)', 'SATCAT: Space-Track user agreement; GCAT: CC BY 4.0, cite J. C. McDowell'],
  set: ['Space Environment Technologies SOLFSMY.TXT and DTCFILE.TXT (2026-10-09)', 'SET: free with a 45-day lag; cite SET and Bowman et al. (2008)'],
  gfz: ['GFZ Kp, ap, Ap, F10.7 since 1932 (Matzka et al. 2021)', 'CC BY 4.0, doi:10.5880/Kp.0001'],
  rsga: ['NOAA SWPC Report of Solar-Geophysical Activity (warehouse 2025, daily 2026)', 'US public domain (weather.gov/disclaimer)'],
  densities: ['ESA Swarm DNSxPOD and GRACE-FO DNS1ACC; Licata et al. (2021) CHAMP and GRACE-A with HASDM', 'ESA EO data terms; Zenodo 10.5281/zenodo.4602380 CC BY 4.0'],
  e5: ['E5 calibration bins (results/e5/calibration)', 'MIT (this repository)'],
  estimates: ['E8 step 10 runs (by config hash)', 'MIT (this repository)'],
  pool: ['E8 step 08 runs (by config hash)', 'MIT (this repository)'],
  kernel: ['JPL DE440s (de440s.bsp)', 'JPL/NAIF, public'],
  eop: ['IERS EOP 20 C04', 'IERS, attribution'],
  reference: ['Precise orbits: ESA Swarm, Copernicus Sentinel-1 POEORB, ILRS NSGF arcs, IDS/CNES DORIS POE, GFZ ISDC RSO, UCAR COSMIC-2 NRT, converted by analysis/reference-states', 'ESA EO terms; Copernicus (EU 1159/2013); ILRS; IDS/CNES; GFZ ISDC; UCAR COSMIC (doi:10.5065/T353-C093)'],
  destopy: ['DESTOPy densities (github.com/pengmun/DESTOPy, MIT), run locally for the cross-check', 'MIT'],
};
const files = {};
for (const name of fs.readdirSync(dir).filter((n) => n.endsWith('.manifest.json')).sort()) {
  const m = JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8'));
  for (const [family, entries] of Object.entries(m.inputs ?? {})) {
    for (const [file, hash] of Object.entries(entries)) {
      const key = `${family}/${file}`;
      files[key] ??= { family, file, sha256: hash, runs: [] };
      if (files[key].sha256 !== hash) files[key].conflict = true;
      files[key].runs.push(m.run);
    }
  }
}
const out = path.join(repoRoot, 'data/e8');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'MANIFEST.json'), `${JSON.stringify({ generated: new Date().toISOString(), files: Object.values(files) }, null, 1)}\n`);
const byFamily = Object.values(files).reduce((a, f) => { (a[f.family] ??= []).push(f); return a; }, {});
const lines = ['# E8 inputs', '', 'Generated by `experiments/e8-omm-density/steps/95-sources.mjs` from the run manifests in `results/e8/manifests`. Every file E8 read, by family, with its SHA-256 in [MANIFEST.json](MANIFEST.json). Nothing here is redistributed; element sets are listed by hash only.', '',
  '| Family | Files | Source | Terms |', '| --- | ---: | --- | --- |'];
for (const [family, list] of Object.entries(byFamily).sort()) {
  const [source, terms] = FAMILIES[family] ?? [family, ''];
  lines.push(`| ${family} | ${list.length} | ${source} | ${terms} |`);
}
fs.writeFileSync(path.join(out, 'SOURCES.md'), `${lines.join('\n')}\n`);
console.log(`data/e8: ${Object.keys(files).length} files in ${Object.keys(byFamily).length} families`);
