// The runner (PLAN.md sections 2-5). One window at cutoff E of a satellite, per arm of its family: the fit on the last 24 h of the latest ESA arc ending by E (t_in), and one FFM forecast from the fit with its
// covariance carried to the six leads; errors against ESA's next arcs and GFZ rapid orbits, in the predicted RTN axes, by gp-error-model. FFM: RK78, relative tolerance 1e-10, steps up to 120 s; fit track at 600 s; outputs at the leads.
// Rows: <store>/rows/s<k>.jsonl. Statistics live in score.mjs.
//   node experiments/ffm-srp-seed-high-beta/run.mjs --launch [--workers 8]     detached, PID file <store>/logs/run.pids.json
//   node experiments/ffm-srp-seed-high-beta/run.mjs --phase window --shard k/n [--limit m]
//   node experiments/ffm-srp-seed-high-beta/run.mjs --check                    the E2E: one stored window per arm replayed bit for bit, the table regenerated byte for byte, the integrity guards live
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { config, store, results, root, dir, args, registered, registeredRef, commitOf, c3, Opened, openSun, sha256, DAY, HOUR, iso, readJsonl } from './common.mjs';

const { arcsOf, windowOf, msOf } = c3.chain;
const RUNNER = ['PLAN.md', 'config.json', 'build.json', 'common.mjs', 'run.mjs'];
const rowsDir = path.join(store, 'rows');
const dayMs = (d) => Date.parse(`${d}T00:00:00Z`);
const SPAN = { fromMs: dayMs(config.truth.arcsFrom), toMs: dayMs(config.truth.arcsTo), allowedToMs: dayMs(config.truth.allowedTo) + DAY };
const GLONASS = Object.keys(config.satellites.glonass).map(Number);
export const familyOf = (norad) => (GLONASS.includes(norad) ? 'glonass' : 'galileo');
const armsOf = (family) => Object.keys(config.arms).filter((a) => config.arms[a].family === family);

const span = (from, to, step) => { const out = []; for (let t = dayMs(from); t <= dayMs(to); t += step * DAY) out.push(t); return out; };
/** Every window: the grid on all satellites and the daily lists, in satellite then date order; onGrid says which cutoffs are the 3-day grid's. */
export function allWindows() {
  const grid = new Set(span(config.grid.from, config.grid.to, config.grid.everyDays));
  const cutoffs = new Map([...GLONASS, ...config.satellites.galileo].map((n) => [n, new Set(grid)]));
  for (const d of config.daily) for (const n of d.norads) for (const E of span(d.from, d.to, 1)) cutoffs.get(n).add(E);
  return [...cutoffs].flatMap(([norad, s]) => [...s].sort((a, b) => a - b).map((E) => ({ norad, E, onGrid: grid.has(E) })));
}

/** An arm's seed and fit settings: C3's settingsFor('R3') (C2's R3 fit) with the arm's seed, and the arm's prior sigma on AGOM. */
export function armSettings(arm, norad, B2C) {
  const a = config.arms[arm];
  const seed = a.family === 'glonass' ? config.seeds.glonass[a.seed] : config.seeds.galileo[String(norad)];
  if (!seed) throw new Error(`no seed for ${arm} ${norad}`);
  const settings = c3.open.settingsFor('R3', { agomSeed: seed }, false, B2C);
  const last = settings.apriori.length - 1;
  settings.apriori[last] = (a.priorFraction * seed) ** 2;
  return { seed, priorSigma: a.priorFraction * seed, settings };
}
/** The fit settings must be the registered ones: a change in anything they come from refuses the run. */
function checkSettings(B2C) {
  const { settings: s } = armSettings('A0', GLONASS[0], B2C), f = config.fit, same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
  const ok = s.sigmaM === f.sigmaM && same(s.fixed, f.fixed) && s.maximumIterations === f.maximumIterations && s.correctionTolerance === f.correctionTolerance && s.sigmaEditThreshold === f.sigmaEditThreshold
    && same(s.forces, f.forces) && same(s.integrator, f.integrator) && s.apriori[0] === f.apriori.positionSigmaM ** 2 && s.apriori[3 * 8] === f.apriori.velocitySigmaMS ** 2;
  if (!ok) throw new Error('the fit settings are not the registered ones');
}

const fitInput = (lines) => ({ points: lines.map((l) => ({ time: l.epoch, position: l.r.map((x) => x * 1000) })), reference: { epoch: lines[0].epoch, state: [...lines[0].r, ...lines[0].v].map((x) => x * 1000) } });

export async function openSession(opened) {
  const { b2 } = await import(path.join(root, 'experiments/ffm-covariance-calibration/lib/precise.mjs'));
  const { fitV3 } = await import(path.join(root, 'harness/ffm-fit-v3.mjs'));
  const B2C = JSON.parse(fs.readFileSync(b2('config.json')));
  checkSettings(B2C);
  const chain = await c3.open.openChain('pin', { opened });
  const arcsCache = new Map();
  return { chain, B2C, fitV3, sunAt: await openSun(opened), gfzAt: c3.gfz.openGfz(opened, config.truth.gfz),
    arcsFor: (norad) => { if (!arcsCache.has(norad)) { if (arcsCache.size > 2) arcsCache.delete(arcsCache.keys().next().value); arcsCache.set(norad, arcsOf(norad, { ...SPAN, opened })); } return arcsCache.get(norad); } };
}

const unit = (a) => { const n = Math.hypot(...a); return a.map((x) => x / n); };
const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const m = (v) => v.map((x) => x * 1000);

/** The rows of one window, one per arm of its family. */
export async function runWindow(S, { norad, E, onGrid }) {
  const family = familyOf(norad), arms = armsOf(family);
  const win = windowOf(norad, S.arcsFor(norad), E, { leadToleranceSeconds: config.truth.leadToleranceSeconds, leads_h: config.leads_h, minCoverage: config.truth.minCoverage });
  const head = { norad, family, E: iso(E), onGrid, tIn: win.tIn ?? null, product: win.product ?? null, coverage: win.coverage ?? null };
  if (win.excluded) return arms.map((arm) => ({ ...head, arm, excluded: win.excluded }));
  const tIn = win.tInMs, end = win.track.at(-1), sunM = await S.sunAt(tIn);
  const betaDeg = (Math.asin(dot(unit(sunM), unit(cross(end.r, end.v)))) * 180) / Math.PI;
  const ctx = S.chain.ctxFor(tIn - 24 * HOUR, tIn + 72 * HOUR), { points, reference } = fitInput(win.track);
  const leads = win.leads.filter((l) => l.line), epochs = leads.map((l) => msOf(l.line.epoch));
  const rows = [];
  for (const arm of arms) {
    const { seed, priorSigma, settings } = armSettings(arm, norad, S.B2C);
    const row = { ...head, arm, betaDeg, sunM, seed, priorSigma, seconds: {} };
    try {
      let t0 = Date.now();
      const f = await S.fitV3(ctx, points, reference, settings);
      row.seconds.fit = (Date.now() - t0) / 1000;
      row.fit = { ok: f.ok, termination: f.termination ?? null, error: f.error ?? null, state: f.state ?? null, agom: f.parameters?.[0]?.value ?? null, agomSigma: f.covariance?.length === 49 ? Math.sqrt(f.covariance[48]) : null, reducedChiSquare: f.reducedChiSquare ?? null, weightedRms: f.weightedRms ?? null, iterations: f.iterations ?? null, ffmCalls: f.ffmCalls ?? null, rejectedTrials: f.rejectedTrials ?? null, refusedTrials: f.refusedTrials ?? null, covarianceSha256: f.covariance ? sha256(Buffer.from(Float64Array.from(f.covariance).buffer)) : null };
      if (f.ok) {
        t0 = Date.now();
        const carried = new Map((await c3.terms.carry(ctx, f, epochs, settings)).map((c) => [c.epochMs, c]));
        const pairs = [], keys = [];
        leads.forEach((l, i) => {
          const c = carried.get(epochs[i]), predicted = { position: c.state.slice(0, 3), velocity: c.state.slice(3, 6), covariance: c.covariance, covarianceAxes: 'INERTIAL' };
          pairs.push({ predicted, truth: { position: m(l.line.r), velocity: m(l.line.v) } }); keys.push([i, 'esa']);
          const g = S.gfzAt(norad, l.line.epoch);
          if (g) { pairs.push({ predicted, truth: { position: g.state.slice(0, 3), velocity: g.state.slice(3, 6) } }); keys.push([i, 'gfz']); }
        });
        const out = leads.map((l) => ({ L: l.L, epoch: l.line.epoch, errRtnM: null, gfzRtnM: null, covRtn: null }));
        (await S.chain.pairs.stats(pairs, 'predicted')).forEach((s, k) => { const [i, kind] = keys[k]; if (kind === 'esa') { out[i].errRtnM = s.errorRtn; out[i].covRtn = s.predictedRtn; } else out[i].gfzRtnM = s.errorRtn; });
        row.leads = out;
        row.seconds.forecast = (Date.now() - t0) / 1000;
      }
    } catch (error) { row.refused = String(error.message).slice(0, 240); }
    rows.push(row);
  }
  return rows;
}

const strip = (r) => { const { seconds, ...rest } = r; return rest; };
async function check() {
  registered([...RUNNER, 'score.mjs']);
  const failures = [];
  const refuses = (what, fn) => { try { fn(); failures.push(`${what}: not refused`); } catch { /* refused, as it must be */ } };
  // the integrity guards are live
  const probe = new Opened();
  refuses('C3 rows', () => probe.add('/opt/data/sdn-archive/ffm-covariance-adaptive/rows/calibration.s0.jsonl'));
  refuses('C3 results', () => probe.add(path.join(root, 'results/ffm-covariance-adaptive/fit-R3.json')));
  refuses('C2 rows', () => probe.add('/opt/data/sdn-archive/ffm-covariance-calibration/rows/R3.calibration.s0.jsonl'));
  refuses('truth after 2026-05-31', () => arcsOf(54377, { ...SPAN, toMs: dayMs('2026-06-15') }));
  probe.add(path.join(config.primary.noticesDir, 'gsc-rows.json'));
  // every window of every arm is in the store, one row each
  const rows = fs.existsSync(rowsDir) ? fs.readdirSync(rowsDir).filter((f) => f.endsWith('.jsonl')).sort().flatMap((f) => readJsonl(path.join(rowsDir, f))) : [];
  if (!rows.length) { console.error(`--check needs this experiment's rows: none under ${rowsDir}. Not a pass.`); process.exit(2); }
  const want = allWindows().flatMap((w) => armsOf(familyOf(w.norad)).map((arm) => `${w.norad}|${iso(w.E)}|${arm}`)), have = new Set(rows.map((r) => `${r.norad}|${r.E}|${r.arm}`));
  if (have.size !== rows.length) failures.push(`${rows.length} rows, ${have.size} distinct`);
  for (const k of want) if (!have.has(k)) failures.push(`no row for ${k}`);
  // one stored window per arm, bit for bit
  const opened = new Opened(), S = await openSession(opened);
  const seen = [];
  for (const [norad, day] of [[54377, '2026-01-07'], [41859, '2026-01-07']]) {
    const E = dayMs(day), got = await runWindow(S, { norad, E, onGrid: rows.find((r) => r.norad === norad && r.E === iso(E)).onGrid });
    for (const g of got) {
      const stored = rows.find((x) => x.norad === g.norad && x.E === g.E && x.arm === g.arm);
      seen.push(g.arm);
      if (JSON.stringify(strip(g)) !== JSON.stringify(strip(stored))) failures.push(`${g.arm} ${g.norad} ${g.E}: the replayed row differs from the stored row`);
    }
  }
  // the table, byte for byte
  const { buildTable, renderTable } = await import('./score.mjs');
  const table = buildTable(rows, new Opened());
  const tableFile = path.join(results, 'table.json');
  if (!fs.existsSync(tableFile)) failures.push(`no ${tableFile}`);
  else if (`${JSON.stringify(table, null, 1)}\n` !== fs.readFileSync(tableFile, 'utf8')) failures.push('table.json differs from the table regenerated from the rows');
  else if (renderTable(table) !== fs.readFileSync(path.join(results, 'table.md'), 'utf8')) failures.push('table.md differs from the table rendered from table.json');
  if (failures.length) { console.error(failures.slice(0, 30).join('\n')); process.exit(1); }
  console.log(`SRP --check: ${rows.length} rows, ${seen.join(', ')} replayed bit for bit at ${commitOf().slice(0, 12)}; table regenerated byte for byte; the integrity guards refuse C3's and C2's rows and results and truth after ${config.truth.allowedTo}`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (args.check) { await check(); process.exit(0); }
  registered(RUNNER);
  if (args.launch) {
    const workers = Number(args.workers ?? config.workers);
    if (workers > 8) throw new Error('at most 8 workers');
    fs.mkdirSync(path.join(store, 'logs'), { recursive: true });
    const pids = [];
    for (let k = 0; k < workers; k += 1) {
      const log = fs.openSync(path.join(store, 'logs', `s${k}.log`), 'a');
      const p = spawn('nice', ['-n', '5', process.execPath, '--max-old-space-size=4096', path.join(dir, 'run.mjs'), '--phase', 'window', '--shard', `${k}/${workers}`], { cwd: root, detached: true, stdio: ['ignore', log, log], env: process.env });
      p.unref();
      pids.push({ pid: p.pid, shard: `${k}/${workers}` });
    }
    fs.writeFileSync(path.join(store, 'logs', 'run.pids.json'), JSON.stringify({ started: new Date().toISOString(), registeredRef, commit: commitOf(), pids }, null, 1));
    console.log(JSON.stringify(pids));
    process.exit(0);
  }
  if (args.phase === 'window') {
    const opened = new Opened();
    const [k, n] = (args.shard ?? '0/1').split('/').map(Number);
    fs.mkdirSync(rowsDir, { recursive: true });
    const out = path.join(rowsDir, `s${k}.jsonl`);
    const done = new Set(readJsonl(out).map((r) => `${r.norad}|${r.E}|${r.arm}`));
    const S = await openSession(opened);
    const windows = allWindows();
    let count = 0;
    for (let i = 0; i < windows.length; i += 1) {
      const w = windows[i];
      if (i % n !== k) continue;
      if (args.limit && count >= Number(args.limit)) break;
      const arms = armsOf(familyOf(w.norad));
      if (arms.every((arm) => done.has(`${w.norad}|${iso(w.E)}|${arm}`))) continue;
      const t0 = Date.now();
      const rows = await runWindow(S, w);
      fs.appendFileSync(out, rows.filter((r) => !done.has(`${r.norad}|${r.E}|${r.arm}`)).map((r) => `${JSON.stringify(r)}\n`).join(''));
      count += 1;
      if (count % 10 === 0) console.error(`shard ${k}/${n}: ${count} windows, last ${w.norad} ${iso(w.E).slice(0, 10)}, ${((Date.now() - t0) / 1000).toFixed(1)} s`);
    }
    fs.mkdirSync(path.join(store, 'opened'), { recursive: true });
    fs.writeFileSync(path.join(store, 'opened', `s${k}.json`), JSON.stringify(opened.list()));
    console.error(`shard ${k}/${n}: finished, ${count} windows`);
    process.exit(0);
  }
  console.error('--launch | --phase window --shard k/n | --check');
  process.exit(2);
}
