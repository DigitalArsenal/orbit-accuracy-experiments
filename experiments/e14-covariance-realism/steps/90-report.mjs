#!/usr/bin/env node
// E14 step 90: the README of a window, generated from its realism files (never typed). Per source: the tally of every
// candidate and the regime x horizon table of each (mean d^2/3 with its interval, 95 % coverage, n and objects, the
// decision), the chosen candidate first.
//
//   node experiments/e14-covariance-realism/steps/90-report.mjs --window devSelect
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { repoRoot } from '../../../harness/provenance.mjs';
import { config } from '../common.mjs';

const { values } = parseArgs({ options: { window: { type: 'string' } } });
const dir = path.join(repoRoot, 'results/e14', values.window.replace(':', '-'));
const selectionFile = path.join(repoRoot, 'results/e14/selection.json');
const selection = fs.existsSync(selectionFile) ? JSON.parse(fs.readFileSync(selectionFile, 'utf8')) : null;
const REG = config.regimes.map((r) => r.id);
const fmt = (c) => {
  if (!c) return '–';
  if (!c.meanD2Over3) return `– (n ${c.n})`;
  const m = c.meanD2Over3, v = c.coverage95;
  const mark = c.decision === 'REALISTIC' ? '**' : '';
  return `${mark}${m.estimate.toPrecision(3)} [${m.lower.toPrecision(3)}, ${m.upper.toPrecision(3)}] / ${v.estimate.toFixed(3)}${mark} (${c.n}, ${c.objects})`;
};
const lines = [`# E14 ${values.window}`, '', `Generated by \`experiments/e14-covariance-realism/steps/90-report.mjs\` from the realism files in this directory. Do not edit by hand. Plan: [PLAN.md](../../../experiments/e14-covariance-realism/PLAN.md).`, '',
  'Cells: mean d²/3 [95 % cluster-bootstrap interval] / 95 % coverage (samples, objects); **bold** = REALISTIC (mean d²/3 in [0.8, 1.25] and coverage in [0.93, 0.97], at least 30 samples from 3 objects). Primary samples: manoeuvre-screened (S2, S3); S1 pairs all count.', ''];
function section(title, chosen, candidates, tableOf, horizons) {
  lines.push(`## ${title}`, '');
  if (chosen) lines.push(`Chosen on dev-select: **${chosen}**.`, '');
  lines.push('| Candidate | Cells | Testable | Realistic |', '| --- | ---: | ---: | ---: |');
  for (const [name, t] of candidates) lines.push(`| ${name} | ${t.cells} | ${t.testable} | ${t.realistic} |`);
  lines.push('');
  const ordered = [...candidates].sort((a, b) => (a[0] === chosen ? -1 : b[0] === chosen ? 1 : 0));
  for (const [name] of ordered) {
    const table = tableOf(name);
    if (!table) continue;
    lines.push(`### ${name}`, '', `| Regime | ${horizons.map((h) => `${h} d`).join(' | ')} |`, `| --- | ${horizons.map(() => '---').join(' | ')} |`);
    for (const r of REG) if (table[r]) lines.push(`| ${r} | ${horizons.map((h) => fmt(table[r][h])).join(' | ')} |`);
    lines.push('');
  }
}
const H = config.horizonsDays.map(String);
const s3 = path.join(dir, 's3-realism.json');
if (fs.existsSync(s3)) {
  const r = JSON.parse(fs.readFileSync(s3, 'utf8'));
  section('S3 — element-set objects (SGP4 with a synthesized covariance)', selection?.sources?.S3?.candidate, Object.entries(r.candidates).map(([k, v]) => [k, v.tally]), (n) => r.candidates[n].primary, H);
}
const s2 = path.join(dir, 's2-realism.json');
if (fs.existsSync(s2)) {
  const r = JSON.parse(fs.readFileSync(s2, 'utf8'));
  section('S2 — the HPOP screen product (epoch state, full force)', selection?.sources?.S2?.candidate, Object.entries(r.candidates).map(([k, v]) => [k, v.tally]), (n) => r.candidates[n].primary, H);
}
const s1 = path.join(dir, 's1-realism.json');
if (fs.existsSync(s1)) {
  const r = JSON.parse(fs.readFileSync(s1, 'utf8'));
  for (const operator of ['starlink', 'planet']) {
    const cands = Object.entries(r.candidates).filter(([, v]) => v[operator]).map(([k, v]) => [k, v[operator].tally]);
    if (cands.length) section(`S1 — ${operator} (stated covariance, scaled)`, selection?.sources?.S1?.byOperator?.[operator]?.candidate, cands, (n) => r.candidates[n][operator]?.table, Object.keys(config.s1HorizonBinsDays));
  }
}
for (const extra of ['s4-density.json', 's4-dcp-summary.json']) {
  const f = path.join(dir, extra);
  if (fs.existsSync(f)) lines.push(`## ${extra}`, '', '```json', JSON.stringify(JSON.parse(fs.readFileSync(f, 'utf8')), null, 1).slice(0, 4000), '```', '');
}
fs.writeFileSync(path.join(dir, 'README.md'), `${lines.join('\n')}\n`);
console.log(`wrote ${path.relative(repoRoot, path.join(dir, 'README.md'))}`);
