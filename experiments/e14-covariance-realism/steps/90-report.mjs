#!/usr/bin/env node
// E14 step 90: the README of a window, generated from its realism files (never typed). Per source: the tally of every
// candidate and the regime x horizon table of each (mean d^2/3 with its interval, 95 % coverage, n and objects, the
// decision), the chosen candidate first.
//
//   node experiments/e14-covariance-realism/steps/90-report.mjs --window devSelect
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { repoRoot } from '../../../harness/provenance.mjs';
import { config } from '../common.mjs';

const { values } = parseArgs({ options: { window: { type: 'string' } } });
const dir = path.join(repoRoot, 'results/e14', values.window.replace(':', '-'));
const selectionFile = path.join(repoRoot, 'results/e14/selection.json');
const selection = fs.existsSync(selectionFile) ? JSON.parse(fs.readFileSync(selectionFile, 'utf8')) : null;
const REG = config.regimes.map((r) => r.id);
const fmt = (c) => {
  if (!c) return '–';
  if (!c.meanD2Over3) return `– (n ${c.n})`;
  const m = c.meanD2Over3, v = c.coverage95;
  const mark = c.decision === 'REALISTIC' ? '**' : '';
  return `${mark}${m.estimate.toPrecision(3)} [${m.lower.toPrecision(3)}, ${m.upper.toPrecision(3)}] / ${v.estimate.toFixed(3)}${mark} (${c.n}, ${c.objects})`;
};
const lines = [`# E14 ${values.window}`, '', `Generated by \`experiments/e14-covariance-realism/steps/90-report.mjs\` from the realism files in this directory. Do not edit by hand. Plan: [PLAN.md](../../../experiments/e14-covariance-realism/PLAN.md).`, '',
  'Cells: mean d²/3 [95 % cluster-bootstrap interval] / 95 % coverage (samples, objects); **bold** = REALISTIC (mean d²/3 in [0.8, 1.25] and coverage in [0.93, 0.97], at least 30 samples from 3 objects). Primary samples: manoeuvre-screened (S2, S3); S1 pairs all count.', ''];
function section(title, chosen, candidates, tableOf, horizons) {
  lines.push(`## ${title}`, '');
  if (chosen) lines.push(`Chosen on dev-select: **${chosen}**.`, '');
  lines.push('| Candidate | Cells | Testable | Realistic |', '| --- | ---: | ---: | ---: |');
  for (const [name, t] of candidates) lines.push(`| ${name} | ${t.cells} | ${t.testable} | ${t.realistic} |`);
  lines.push('');
  const ordered = [...candidates].sort((a, b) => (a[0] === chosen ? -1 : b[0] === chosen ? 1 : 0));
  for (const [name] of ordered) {
    const table = tableOf(name);
    if (!table) continue;
    lines.push(`### ${name}`, '', `| Regime | ${horizons.map((h) => `${h} d`).join(' | ')} |`, `| --- | ${horizons.map(() => '---').join(' | ')} |`);
    for (const r of REG) if (table[r]) lines.push(`| ${r} | ${horizons.map((h) => fmt(table[r][h])).join(' | ')} |`);
    lines.push('');
  }
}
const H = config.horizonsDays.map(String);
const s3 = path.join(dir, 's3-realism.json');
if (fs.existsSync(s3)) {
  const r = JSON.parse(fs.readFileSync(s3, 'utf8'));
  section('S3 — element-set objects (SGP4 with a synthesized covariance)', selection?.sources?.S3?.candidate, Object.entries(r.candidates).map(([k, v]) => [k, v.tally]), (n) => r.candidates[n].primary, H);
}
const s2 = path.join(dir, 's2-realism.json');
if (fs.existsSync(s2)) {
  const r = JSON.parse(fs.readFileSync(s2, 'utf8'));
  section('S2 — the FFM screen product (epoch state, full force)', selection?.sources?.S2?.candidate, Object.entries(r.candidates).map(([k, v]) => [k, v.tally]), (n) => r.candidates[n].primary, H);
}
const s1 = path.join(dir, 's1-realism.json');
if (fs.existsSync(s1)) {
  const r = JSON.parse(fs.readFileSync(s1, 'utf8'));
  for (const operator of ['starlink', 'planet']) {
    const cands = Object.entries(r.candidates).filter(([, v]) => v[operator]).map(([k, v]) => [k, v[operator].tally]);
    if (cands.length) section(`S1 — ${operator} (stated covariance, scaled)`, selection?.sources?.S1?.byOperator?.[operator]?.candidate, cands, (n) => r.candidates[n][operator]?.table, Object.keys(config.s1HorizonBinsDays));
  }
}
// The probability-of-collision effect (descriptive) of the candidates scored with --pc.
const pcLines = (title, r) => {
  const cands = Object.entries(r.candidates).filter(([, v]) => v.pcEffect);
  if (!cands.length) return;
  lines.push(`## ${title}: probability-of-collision effect (descriptive)`, '',
    'Per cell, 500 pairs of samples of different objects, each with its own covariance (gp-error-model screening_cases, E2b\'s rules: hard body 20 m, alert Pc >= 1e-4). Head-on plane: alert rate on true collisions (misses 0 and 10 m) / alert rate at a 1 km true miss.', '');
  for (const [name, v] of cands) {
    lines.push(`### ${name}`, '', `| Regime | ${H.map((h) => `${h} d`).join(' | ')} |`, `| --- | ${H.map(() => '---').join(' | ')} |`);
    for (const g of REG) if (v.pcEffect[g]) lines.push(`| ${g} | ${H.map((h) => { const c = v.pcEffect[g][h]?.['head-on']; return c ? `${c.pcAlertRateCollisions.toFixed(2)} / ${c.pcAlertRate1km.toFixed(3)}` : '–'; }).join(' | ')} |`);
    lines.push('');
  }
};
if (fs.existsSync(s3)) pcLines('S3', JSON.parse(fs.readFileSync(s3, 'utf8')));
if (fs.existsSync(s2)) {
  const r = JSON.parse(fs.readFileSync(s2, 'utf8'));
  pcLines('S2', r);
  if (r.h5) {
    lines.push('## H5: the DCP under forecast storms (LEO)', '', `${r.h5.rule}: ${r.h5.n} samples, ${r.h5.objects} objects (issue class 2: ${r.h5.byReason.predicted}; observed only: ${r.h5.byReason.observedOnly}).`, '',
      '| Candidate | n | objects | mean d²/3 S2-QC | mean d²/3 S2-QCD | \\|ln\\| difference [95 %] | Decision |', '| --- | ---: | ---: | ---: | ---: | --- | --- |');
    for (const [k, x] of Object.entries(r.h5.shrinkage)) lines.push(x.difference ? `| ${k} | ${x.n} | ${x.objects} | ${x.meanD2Over3QC.toPrecision(3)} | ${x.meanD2Over3QCD.toPrecision(3)} | ${x.difference.estimate.toPrecision(3)} [${x.difference.lower.toPrecision(3)}, ${x.difference.upper.toPrecision(3)}] | ${x.decision} |` : `| ${k} | ${x.n} | ${x.objects} | – | – | – | ${x.decision} |`);
    lines.push('');
  }
}
const s4d = path.join(dir, 's4-density.json');
if (fs.existsSync(s4d)) {
  const r = JSON.parse(fs.readFileSync(s4d, 'utf8'));
  lines.push('## H6: the DCP\'s density error against independent densities', '', 'z = ln(ρ_obs / ρ_NRLMSISE(released drivers)) / sqrt(σ_m² + C_δ[k][k]), daily means along track (Swarm A/B/C POD, GRACE-FO 1 ACC; ESA).', '',
    '| Lead day | n | satellites | 95 % coverage | without C_δ | mean z² | Within [0.93, 0.97] |', '| ---: | ---: | ---: | ---: | ---: | ---: | --- |');
  for (const [k, l] of Object.entries(r.leads)) lines.push(`| ${k} | ${l.n} | ${l.satellites} | ${l.coverage95.toFixed(3)} | ${l.coverage95ModelOnly.toFixed(3)} | ${l.meanZ2.toFixed(2)} | ${l.supported === null ? 'INSUFFICIENT' : l.supported ? 'yes' : 'no'} |`);
  lines.push('', `σ_m (dev-fit, ln ρ with observed drivers): ${Object.entries(r.sigmaModel).map(([k, v]) => `${k} ${v.rms.toFixed(3)} (bias ${v.mean.toFixed(3)}, n ${v.n})`).join('; ')}.`, '');
}
const s4s = path.join(dir, 's4-dcp-summary.json');
if (fs.existsSync(s4s)) {
  const r = JSON.parse(fs.readFileSync(s4s, 'utf8'));
  lines.push('## S4: the lead covariance on this window\'s issues (descriptive)', '', `${r.issues} issues (${r.span?.join(' to ')}). Per altitude and forecast class: share of |δ_k| within 1.96 σ_k / mean δ_k²/σ_k², lead days 1–7.`, '',
    '| Altitude (km) | Class | n | 1 | 2 | 3 | 4 | 5 | 6 | 7 |', '| ---: | ---: | ---: | --- | --- | --- | --- | --- | --- | --- |');
  for (const st of r.strata) if (st.n) lines.push(`| ${st.altitudeKm} | ${st.class} | ${st.n} | ${st.leads.map((l) => `${l.coverage95.toFixed(2)} / ${l.meanZ2.toFixed(2)}`).join(' | ')} |`);
  lines.push('');
}
// The hypotheses (step 85), on the test README.
const hyp = path.join(repoRoot, 'results/e14/hypotheses.json');
if (values.window === 'test' && fs.existsSync(hyp)) {
  const H = JSON.parse(fs.readFileSync(hyp, 'utf8')).hypotheses;
  const verdict = (h) => h?.verdict ?? (h && typeof h === 'object' ? Object.entries(h).map(([k, v]) => `${k}: ${v.verdict}`).join('; ') : '–');
  lines.splice(6, 0, '## Hypotheses (PLAN.md section 9; step 85)', '', '| | Verdict | Numbers |', '| --- | --- | --- |',
    `| H1 S3 realistic | ${verdict(H.H1)} | ${H.H1 ? `${H.H1.realistic} of ${H.H1.testable} testable cells REALISTIC (${H.H1.candidate})` : ''} |`,
    `| H2 S2 realistic | ${verdict(H.H2)} | ${H.H2 ? `${H.H2.realistic} of ${H.H2.testable} (${H.H2.candidate})` : ''} |`,
    `| H3 S1 realistic | ${verdict(H.H3)} | ${H.H3?.reason ?? ''} |`,
    `| H4 calibration transfers | ${verdict(H.H4)} | ${Object.entries(H.H4 ?? {}).map(([k, v]) => `${k}: ${v.chosen.realistic} vs ${v.base.realistic} realistic, median abs ln mean d2/3 ${v.chosen.medianAbsLnMeanD2Over3?.toFixed(2)} vs ${v.base.medianAbsLnMeanD2Over3?.toFixed(2)}`).join('; ')} |`,
    `| H5 DCP under storms | ${verdict(H.H5)} | ${H.H5?.difference ? `${H.H5.n} samples, ${H.H5.objects} objects: difference ${H.H5.difference.estimate.toExponential(2)} [${H.H5.difference.lower.toExponential(2)}, ${H.H5.difference.upper.toExponential(2)}]` : ''} |`,
    `| H6 density error calibrated | ${verdict(H.H6)} | ${(H.H6?.leads ?? []).map((l) => `lead ${l.lead}: ${l.coverage95.toFixed(3)} (n ${l.n})`).join('; ')} |`,
    `| H7 Starlink in-track pessimistic | ${verdict(H.H7)} | |`,
    `| H8 known answer | ${verdict(H.H8)} | ${(H.H8?.summary ?? []).filter((l) => /pass|fail/.test(l)).join(', ')} |`, '');
}
const ca = path.join(dir, 'ca-pc.json');
if (fs.existsSync(ca)) {
  const r = JSON.parse(fs.readFileSync(ca, 'utf8'));
  lines.push('## The CA screen with the S3 model (step 96)', '', `analysis/conjunction-assessment assess_conjunction, ${r.algorithm}, hard body 5 + 5 m, uncertainty_model ${r.model}.`, '',
    '| Objects | TCA | Miss (m) | Pc | Source | Calibration | sigma RTN each (m) |', '| --- | --- | ---: | ---: | --- | --- | --- |');
  for (const p of r.pairs) lines.push(`| ${p.objects.join(' x ')} | ${p.tca} | ${p.missDistanceM.toFixed(1)} | ${p.probability.toExponential(2)} | ${p.uncertaintySource} | ${p.calibration} | ${p.sigmaRtnM[0].join('/')} |`);
  lines.push('');
}
fs.writeFileSync(path.join(dir, 'README.md'), `${lines.join('\n')}\n`);
console.log(`wrote ${path.relative(repoRoot, path.join(dir, 'README.md'))}`);
