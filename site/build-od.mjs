// The inputs of the "03 // Orbit Determination" pages, written by the site
// build. Every number comes from a module; this file selects public records
// and frames them.
//
//  - truth.oem      IGS final GPS orbits for 2026-08-02 as GCRF/UTC states with
//                   their stated covariance (analysis/reference-states output in
//                   the SDN archive), 05:15-10:45 UTC.
//  - truth-dense.json  The same satellites between the IGS epochs, 60 s apart:
//                   propagator/hpop from each IGS state to the next (15 min),
//                   so the trajectory meets the IGS orbit at every IGS epoch.
//  - catalog.oem    The catalog the observations are associated with: each GPS
//                   satellite's IGS state at 2026-08-01 23:59:42 UTC propagated
//                   by propagator/hpop with a covariance (1 m, 1 mm/s, white
//                   acceleration noise), sampled every 5 min, 05:29:42-10:29:42 UTC (on the IGS grid).
//                   Two satellites are withheld, so their observations are
//                   uncorrelated by construction.
//  - simulate.acw   An analysis/observation-simulator request: the dense truth
//                   rotated to ITRF by foundation/frames, three sensors at IGS
//                   sites, their visibility from analysis/access, the Sun from
//                   propagator/hpop's DE440 ephemeris, the IERS rows.
//  - eop.json, eop.prw  IERS EOP 20 C04 rows for the day, as $EOP objects and
//                   as a PRW EARTH_ORIENTATION frame.
//  - scenario.json  What is where: sites, sensors, satellites, windows,
//                   withheld satellites, sources.
import fs from 'node:fs';
import path from 'node:path';
import createFlatc from 'flatc-wasm/module';
import { loadModule } from '../harness/modules.mjs';
import { eopFrame } from '../harness/eop.mjs';
import { convertIso } from '../harness/time.mjs';
import {
  ACW, acw, acwTable, geodeticToItrf, decodeAcw, decodeExecution, decodeOem, decodeSun, encodeAcw, encodeOem, eopFrames, executionFrame, frame, isoMicro,
  sunRequest, transformState, utcMs,
} from './src/od/codec.js';

export const OD_DAY = '20262140000';
const IGS = `IGS0OPSFIN_${OD_DAY}_01D_15M_ORB`;
const MIN = 60e3;
// Approximate IGS site positions (WGS-84); they only place the sensors.
export const SITES = [
  { id: 'WTZR', name: 'Wettzell', lat: 49.1442, lon: 12.8789, alt: 666 },
  { id: 'GOLD', name: 'Goldstone', lat: 35.4252, lon: -116.8893, alt: 986 },
  { id: 'YAR2', name: 'Yarragadee', lat: -29.0466, lon: 115.3470, alt: 241 },
];
const DEG = Math.PI / 180, ARCSEC = DEG / 3600;
const model = (type, sigma, extra = {}) => acwTable('MEMErrorModel', { MODEL_ID: type, MEASUREMENT_TYPE: ACW.memMeasurementType[type], NOISE_SIGMA: sigma, APPLY_LIGHT_TIME: false, ...extra });
export const SENSORS = [
  { id: 'WTZR-RADAR', host: 'WTZR', phenomenology: 'RADAR', models: [['RANGE', 10], ['RANGE_RATE', 0.05], ['AZIMUTH_ELEVATION', 0.01 * DEG]], falseAlarms: 1 },
  { id: 'GOLD-OPTICAL', host: 'GOLD', phenomenology: 'OPTICAL', models: [['RIGHT_ASCENSION_DECLINATION', 1 * ARCSEC]], falseAlarms: 1 },
  { id: 'YAR2-RF', host: 'YAR2', phenomenology: 'PASSIVE_RF', models: [['RANGE_RATE', 0.2], ['DOPPLER', 1]], falseAlarms: 1 },
];
export const WITHHELD = 2;

// TypeScript object-API bindings of analysis/estimation's module-local invoke
// schema (Estimation.fbs and the SDK schemas it includes), generated by flatc
// for the pages to encode $EST requests and decode results exactly.
export async function generateEstimationBindings(modules, sdkSchemas, outDir) {
  const flatc = await createFlatc({ print: () => {}, printErr: () => {} });
  flatc.FS.mkdir('/schema');
  flatc.FS.mkdir('/out');
  for (const name of fs.readdirSync(sdkSchemas).filter((n) => n.endsWith('.fbs'))) flatc.FS.writeFile(`/schema/${name}`, fs.readFileSync(path.join(sdkSchemas, name)));
  flatc.FS.writeFile('/schema/Estimation.fbs', fs.readFileSync(path.join(modules, 'analysis/estimation/schemas/Estimation.fbs')));
  if (flatc.callMain(['--ts', '--gen-object-api', '--gen-all', '-I', '/schema', '-o', '/out', '/schema/Estimation.fbs']) !== 0) throw new Error('flatc: Estimation.fbs bindings failed');
  fs.rmSync(outDir, { recursive: true, force: true });
  const copy = (from, to) => {
    fs.mkdirSync(to, { recursive: true });
    for (const name of flatc.FS.readdir(from).filter((n) => n !== '.' && n !== '..')) {
      const source = `${from}/${name}`;
      if (flatc.FS.isDir(flatc.FS.stat(source).mode)) copy(source, path.join(to, name));
      else fs.writeFileSync(path.join(to, name), flatc.FS.readFile(source));
    }
  };
  copy('/out', outDir);
}  // the last two satellites by catalog number are not in the catalog
const L1_HZ = 1575.42e6;

export async function buildOd({ modules, referenceDir, eopRecords, kernelPrw, write, log }) {
  const [hpop, frames, access, simulator, time] = await Promise.all(['propagator/hpop', 'foundation/frames', 'analysis/access', 'analysis/observation-simulator', 'foundation/time']
    .map((m) => loadModule(modules, m)));
  const dir = path.join(referenceDir, IGS);
  const truthBlocks = [];
  for (const name of fs.readdirSync(dir).filter((n) => n.endsWith('.oem')).sort()) {
    const [block] = decodeOem(fs.readFileSync(path.join(dir, name)));
    truthBlocks.push(block);
  }
  truthBlocks.sort((a, b) => a.norad - b.norad);
  const from = utcMs('2026-08-02T05:15:00Z'), to = utcMs('2026-08-02T10:45:00Z');
  const inside = (e) => utcMs(e) >= from && utcMs(e) <= to;
  const truth = truthBlocks.map((b) => ({ ...b, states: b.states.filter((s) => inside(s.epoch)), covariances: b.covariances.filter((c) => inside(c.epoch)) }));
  write('data/od/truth.oem', Buffer.from(encodeOem(truth, { originator: 'IGS final orbits via analysis/reference-states' })),
    `${IGS}.SP3.gz as GCRF/UTC with covariance (analysis/reference-states), 05:15-10:45 UTC`, 'IGS data policy: open, cite the IGS');

  // Earth orientation: the IERS rows of 2026-08-01..03.
  const rows = eopRecords.filter((r) => r.mjd >= 61253 && r.mjd <= 61256).map((r) => r.row);
  write('data/od/eop.json', rows, 'IERS EOP 20 C04 rows MJD 61253-61256 through data-source/eop-parser', 'IERS data, free with attribution');
  const eopPrw = eopFrame(eopRecords, 61253, 61256);
  write('data/od/eop.prw', Buffer.from(eopPrw.payload), 'The same rows as a PRW EARTH_ORIENTATION frame', 'IERS data, free with attribution');
  const eop = eopFrames(rows);
  const hpopInputs = (request) => [executionFrame({ ...request, kernel: true }), { ...eopPrw }, frame('kernel', 'PRW', kernelPrw)];
  const FORCES = { degree: 20, order: 20, thirdBodies: [10, 301], srp: true, massKg: 1500, areaM2: 20, cr: 1.3 };

  // Dense truth: HPOP from each IGS epoch to the next, every 60 s.
  const dense = [];
  for (const b of truth) {
    const states = [];
    for (let k = 0; k + 1 < b.states.length; k++) {
      const a = b.states[k], next = b.states[k + 1];
      const samples = [];
      for (let ms = utcMs(a.epoch) + MIN; ms < utcMs(next.epoch) - 1; ms += MIN) samples.push(isoMicro(ms));
      const run = decodeExecution(await hpop.invoke('invoke', hpopInputs({ epoch: a.epoch, position: a.state.slice(0, 3), velocity: a.state.slice(3), samples, forces: FORCES })), samples);
      states.push({ epoch: a.epoch, state: a.state }, ...run.map((s) => ({ epoch: s.epoch, state: [...s.position, ...s.velocity] })));
    }
    states.push(b.states.at(-1));
    dense.push({ norad: b.norad, objectId: b.objectId, name: b.name, states });
  }
  write('data/od/truth-dense.json', dense.map((b) => ({ norad: b.norad, objectId: b.objectId, name: b.name, epochs: b.states.map((s) => s.epoch),
    position: b.states.flatMap((s) => s.state.slice(0, 3)) })), 'IGS final GPS orbits densified to 60 s by propagator/hpop between IGS epochs', 'IGS data policy: open, cite the IGS');
  log(`od: dense truth for ${dense.length} satellites`);

  // The catalog: HPOP from 23:59:42 with covariance and process noise.
  const catalogEpochs = [];
  for (let ms = utcMs('2026-08-02T05:29:42Z'); ms <= utcMs('2026-08-02T10:29:42Z'); ms += 5 * MIN) catalogEpochs.push(isoMicro(ms));
  const sorted = [...truthBlocks];
  const withheld = sorted.slice(-WITHHELD).map((b) => b.norad);
  const catalog = [];
  const P0 = Array.from({ length: 36 }, (_, q) => (q % 7 ? 0 : q < 21 ? 1e-6 : 1e-12));  // 1 m, 1 mm/s (km units)
  for (const b of sorted.filter((x) => !withheld.includes(x.norad))) {
    const s0 = b.states[0];
    const run = decodeExecution(await hpop.invoke('invoke', hpopInputs({ epoch: s0.epoch, position: s0.state.slice(0, 3), velocity: s0.state.slice(3), samples: catalogEpochs,
      forces: FORCES, covariance: P0, noisePsd: [1e-11, 1e-11, 1e-11], noiseInterval: 60 })), catalogEpochs);
    catalog.push({ norad: b.norad, objectId: b.objectId, name: b.name, comment: `IGS state at ${s0.epoch} UTC propagated by propagator/hpop with covariance`,
      states: run.map((s) => ({ epoch: s.epoch, state: [...s.position, ...s.velocity] })), covariances: run.map((s) => ({ epoch: s.epoch, matrix: s.covariance })) });
  }
  write('data/od/catalog.oem', Buffer.from(encodeOem(catalog, { originator: 'propagator/hpop prediction of IGS states' })),
    `${catalog.length} GPS satellites: IGS state at 2026-08-01T23:59:42Z propagated by propagator/hpop (20x20, Sun, Moon, SRP) with covariance, 05:30-10:30 UTC`, 'IGS data policy: open, cite the IGS');
  log(`od: catalog of ${catalog.length} (withheld ${withheld.join(', ')})`);

  // Time: TT - UTC from foundation/time at one epoch of the day (no leap second in it).
  const ttMinusUtc = (utcMs(await convertIso(time, '2026-08-02T06:00:00.000000', 'UTC', 'TT')) - utcMs('2026-08-02T06:00:00Z')) / 1000;
  const jdTt = (iso) => (utcMs(iso) + ttMinusUtc * 1000) / 86400e3 + 2440587.5;

  // Truth to ITRF (foundation/frames), as the simulator and access want it.
  const sample = (iso, p, v) => acwTable('ACWStateSample', { JULIAN_DATE_TT: jdTt(iso), POSITION_X_M: p[0] * 1000, POSITION_Y_M: p[1] * 1000, POSITION_Z_M: p[2] * 1000,
    VELOCITY_X_MPS: v[0] * 1000, VELOCITY_Y_MPS: v[1] * 1000, VELOCITY_Z_MPS: v[2] * 1000 });
  const simFrom = utcMs('2026-08-02T06:00:00Z'), simTo = utcMs('2026-08-02T10:00:00Z');
  const targets = [];
  for (const b of dense) {
    const states = [];
    for (const s of b.states.filter((x) => utcMs(x.epoch) >= simFrom - 5 * MIN && utcMs(x.epoch) <= simTo + 5 * MIN)) {
      const f = await transformState(frames, eop, { from: 'GCRF', to: 'ITRF', epoch: s.epoch, position: s.state.slice(0, 3), velocity: s.state.slice(3) });
      states.push(sample(s.epoch, f.position, f.velocity));
    }
    targets.push(acwTable('ACWTarget', { TARGET_ID: `G${b.norad}`, NORAD_CAT_ID: b.norad, OBJECT_ID: b.objectId, STATES: states,
      SIGNATURE: acwTable('ACWTargetSignature', { RCS_M2: 10, DIAMETER_M: 3, GEOMETRIC_ALBEDO: 0.2, EMITTER_FREQUENCY_HZ: L1_HZ, EMITTER_EIRP_DBW: 27 }) }));
  }
  log(`od: ${targets.length} targets in ITRF`);

  // The Sun, hourly, from HPOP's DE440 ephemeris, rotated to ITRF.
  const sun = [];
  for (let ms = simFrom - 3600e3; ms <= simTo + 3600e3; ms += 3600e3) {
    const epoch = isoMicro(ms);
    const g = decodeSun(await hpop.invoke('invoke', [sunRequest(await convertIso(time, epoch, 'UTC', 'TDB')), frame('kernel', 'PRW', kernelPrw)]));
    const f = await transformState(frames, eop, { from: 'GCRF', to: 'ITRF', epoch, position: g.position, velocity: g.velocity });
    sun.push(sample(epoch, f.position, [0, 0, 0]));
  }

  // Visibility: analysis/access per target, every site at 10 degrees.
  const stations = SITES.map((s) => acwTable('ACWGroundStation', { STATION_ID: s.id, NAME: s.name, LATITUDE_RAD: s.lat * DEG, LONGITUDE_RAD: s.lon * DEG, ALTITUDE_M: s.alt, MIN_ELEVATION_RAD: 10 * DEG }));
  const accessList = [];
  for (const target of targets) {
    const response = await access.invoke('compute_access_windows', [encodeAcw(acw({ REQUEST: acwTable('ACWRequest', {
      OPERATION: ACW.acwOperationCode.COMPUTE_ACCESS_WINDOWS, GROUND_STATIONS: stations, STATES: target.STATES, EVALUATION_MODE: ACW.acwEvaluationMode.CONTINUOUS }) }))]);
    const result = decodeAcw(response.outputs.find((o) => o.portId === 'results').payload).RESULT;
    for (const sensor of SENSORS) {
      const windows = (result.WINDOWS ?? []).filter((w) => w.STATION_ID === sensor.host);
      if (windows.length) accessList.push(acwTable('ACWSensorAccess', { SENSOR_ID: sensor.id, TARGET_ID: target.TARGET_ID, WINDOWS: windows }));
    }
  }
  log(`od: ${accessList.length} sensor-target access entries`);

  const sensors = SENSORS.map((s) => acwTable('ACWSensor', {
    SENSOR_ID: s.id, HOST_ID: s.host, PHENOMENOLOGY: ACW.acwSensorPhenomenology[s.phenomenology],
    ERROR_MODELS: s.models.map(([type, sigma]) => model(type, sigma)),
    OBSERVATION_INTERVAL_S: 120, TRACK_DURATION_S: 900, REVISIT_INTERVAL_S: 1800, MAX_SIMULTANEOUS_TRACKS: 4,
    DETECTION_THRESHOLD_DB: s.phenomenology === 'PASSIVE_RF' ? 10 : 0, RECEIVER_G_OVER_T_DB_PER_K: -20, RECEIVER_BANDWIDTH_HZ: 1000,
    MAX_HOST_SUN_ELEVATION_RAD: -12 * DEG, FALSE_ALARM_RATE_PER_HOUR: s.falseAlarms,
  }));
  const request = encodeAcw(acw({ REQUEST: acwTable('ACWRequest', {
    OPERATION: ACW.acwOperationCode.SIMULATE_OBSERVATIONS, GROUND_STATIONS: stations, TARGETS: targets, SENSORS: sensors, ACCESS: accessList,
    SUN_STATES: sun, EARTH_ORIENTATION: rows.map((r) => Object.assign(new ACW.EOPT(), r)), RANDOM_SEED: 20261009n,
    START_JULIAN_DATE_TT: jdTt(isoMicro(simFrom)), END_JULIAN_DATE_TT: jdTt(isoMicro(simTo)),
  }) }));
  write('data/od/simulate.acw', Buffer.from(request.payload), 'analysis/observation-simulator request: dense truth in ITRF (foundation/frames), access (analysis/access), Sun (propagator/hpop DE440)', 'IGS and IERS data; MIT');
  // Check the request runs.
  const simulated = await simulator.invoke('simulate_observations', [request]);
  const counts = Object.fromEntries(['radar', 'optical', 'rf'].map((p) => [p, simulated.outputs.filter((o) => o.portId === p).length]));
  log(`od: simulated ${JSON.stringify(counts)}`);

  const sites = [];
  for (const s of SITES) sites.push({ ...s, itrfKm: await geodeticToItrf(frames, s) });
  write('data/od/scenario.json', {
    day: '2026-08-02', truthProduct: IGS, sites, sensors: SENSORS.map(({ id, host, phenomenology, models, falseAlarms }) => ({ id, host, phenomenology, models, falseAlarmsPerHour: falseAlarms })),
    satellites: truthBlocks.map((b) => ({ norad: b.norad, objectId: b.objectId, name: b.name })), withheld, simulation: { from: isoMicro(simFrom), to: isoMicro(simTo), seed: 20261009 },
    catalog: { epoch: truthBlocks[0].states[0].epoch, forces: FORCES, initialSigma: { positionM: 1, velocityMps: 1e-3 }, processNoisePsdM2S3: 1e-11, samples: catalogEpochs.length },
    ttMinusUtcSeconds: ttMinusUtc, counts,
  });
  for (const m of [hpop, frames, access, simulator, time]) await m.destroy();
}
